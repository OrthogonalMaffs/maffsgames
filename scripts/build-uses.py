def build(root):
    """({repo path: text} for every generated file, sitemap.xml included, [refusals])."""
    d = load(root)
    errors = []
    topics, routes = d["topics"], {r["slug"]: r["name"] for r in d["routes"]}
    colours = {r["slug"]: r["colour"] for r in d["routes"]}
    tslugs = {t["slug"] for t in topics}
    for s in d["scenarios"]:
        if s["topic"] not in tslugs:
            errors.append("scenario %s: topic %r is not in topics" % (s.get("id"), s["topic"]))
        if s["route"] is not None and s["route"] not in routes:
            errors.append("scenario %s: route %r is not in routes" % (s.get("id"), s["route"]))
        if s.get("tier") not in TIERS:
            errors.append("scenario %s: tier %r is not one of %s" % (s.get("id"), s.get("tier"), ", ".join(TIERS)))
    for t in topics:
        if t["parentGuide"] and not (root / "parents" / t["parentGuide"] / "index.html").is_file():
            errors.append("topic %s: parent guide parents/%s/ does not exist" % (t["slug"], t["parentGuide"]))
    if errors:
        return {}, errors
    used = [r for r in d["routes"] if any(s["route"] == r["slug"] for s in d["scenarios"])]
    paths = ["%s/index.html" % SECTION] + ["%s/%s/index.html" % (SECTION, t["slug"]) for t in topics] + \
            ["%s/route/%s/index.html" % (SECTION, r["slug"]) for r in used]
    pages = json.loads((root / GAMES).read_text(encoding="utf-8")).get("pages", {})
    for p in paths:
        if p not in pages:
            errors.append("%s has no data/games.json \"pages\" entry (its title and description)" % p)
    for p in sorted(pages):
        if p.startswith(SECTION + "/") and p not in paths:
            errors.append("data/games.json \"pages\" has %s, which build-uses.py does not write" % p)
    if errors:
        return {}, errors
    vals = {p: {"title": pages[p]["title"], "description": pages[p]["description"], "canonical": url(p)} for p in paths}
    live = live_games(root)
    out = {paths[0]: hub_page(d, topics, used, routes, colours, vals[paths[0]])}
    for t in topics:
        p = "%s/%s/index.html" % (SECTION, t["slug"])
        out[p] = topic_page(root, d, t, routes, colours, vals[p], live)
    for r in used:
        p = "%s/route/%s/index.html" % (SECTION, r["slug"])
        out[p] = route_page(d, r, topics, routes, colours, vals[p])
    out = {p: cm.render(t, vals[p]) for p, t in out.items()}
    out[CSS] = USES_CSS
    out[SITEMAP] = sitemap(root, paths)
    portal = count_block(root, len(d["scenarios"]))
    if portal is None:
        return {}, ["%s has no %s ... %s block for the strip's job count" % (PORTAL, COUNT_BEGIN, COUNT_END)]
    out[PORTAL] = portal
    return out, []


def count_block(root, n):
    """index.html with the strip's job count ("N real jobs") between the markers, or None if they are missing."""
    text = (root / PORTAL).read_text(encoding="utf-8")
    a = text.find(COUNT_BEGIN)
    b = text.find(COUNT_END, a) if a >= 0 else -1
    if a < 0 or b < 0:
        return None
    return text[:a + len(COUNT_BEGIN)] + "%d real jobs" % n + text[b:]


def sitemap(root, paths):
    text = (root / SITEMAP).read_text(encoding="utf-8")
    block = SITEMAP_BEGIN + "".join("  <url><loc>%s</loc><changefreq>monthly</changefreq><priority>%s</priority></url>\n"
                                    % (url(p), "0.7" if i == 0 else "0.6") for i, p in enumerate(paths)) + SITEMAP_END
    if SITEMAP_BEGIN in text:
        a = text.index(SITEMAP_BEGIN)
        b = text.index(SITEMAP_END, a) + len(SITEMAP_END)
        return text[:a] + block + text[b:]
    i = text.rindex("</urlset>")
    return text[:i] + block + text[i:]


def stale(root, out):
    """Pages under when-will-i-use-this/ that the build no longer writes."""
    d = root / SECTION
    have = [p.relative_to(root).as_posix() for p in d.rglob("*") if p.is_file()] if d.is_dir() else []
    return sorted(p for p in have if p not in out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    out, errors = build(BASE)
    if errors:
        print("\n".join("REFUSED: " + e for e in errors))
        return 1
    n = 0
    for path, text in out.items():
        p = BASE / path
        if p.is_file() and p.read_text(encoding="utf-8") == text:
            continue
        n += 1
        print("%s %s" % ("would write" if a.dry_run else "wrote   ", path))
        if not a.dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8", newline="")
    for path in stale(BASE, out):
        n += 1
        print("%s %s" % ("would delete" if a.dry_run else "deleted ", path))
        if not a.dry_run:
            (BASE / path).unlink()
    print("%d of %d files %s" % (n, len(out), "would change" if a.dry_run else "changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
