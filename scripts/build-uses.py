#!/usr/bin/env python3
"""Write the "When will I use this?" section (when-will-i-use-this/) from data/uses.json.

    python -X utf8 scripts/build-uses.py            # write
    python -X utf8 scripts/build-uses.py --dry-run  # report what would change

Contract WHEN-WILL-I-USE-THIS (Jon, spec 10 Nov 2026, build 22 Nov 2026). One data file feeds every page, so a
scenario is written once and appears on its topic page and its route page:
  - when-will-i-use-this/index.html: the hub, listing the topics and the routes that have scenarios;
  - when-will-i-use-this/<topic>/index.html: one page per topic: its one-line answer, its scenarios (job, route, text,
    numbered steps), "Practise it" (the live games whose data/games.json keywords match the topic's keywords), "Help
    at home" (its parent guide, if any) and "Sources";
  - when-will-i-use-this/route/<route>/index.html: one page per route with at least one scenario, grouped by topic;
  - sitemap.xml: the block between SITEMAP_BEGIN and SITEMAP_END lists every page above.
The pages are static and committed: nothing is built on deploy. Idempotent: a second run changes nothing. A page under
when-will-i-use-this/ that this script no longer writes is deleted.

Shared, never copied: the look is parents/guide.css and the Aa toggle parents/guide.js (the existing mfg_accessible
key); each head's title, description and og:/twitter: copies are written by scripts/check-meta.py's render() from
data/games.json "pages", so apply-meta.py finds nothing to change; the footer is scripts/check-footer.py's CANONICAL.
Maths in the wording (a run of numbers joined by + − × ÷ = or a spaced ratio colon) is set in KaTeX at display (canon
§7.1.1); the stored wording is never changed. scripts/check-uses.py (CI) holds the pages to this script's output and
recomputes every worked step.

It refuses (exit 1, nothing written) when the data names a topic or route that does not exist, a generated page has no
games.json "pages" entry, or a parent guide folder is missing: those need a person.
"""
import argparse, html, importlib.util, json, pathlib, re, sys

BASE = pathlib.Path(__file__).resolve().parent.parent
DATA = "data/uses.json"
GAMES = "data/games.json"
ROSTER = ".claude/rules/game-roster.md"
SECTION = "when-will-i-use-this"
SITEMAP = "sitemap.xml"
SITE = "https://maffsgames.co.uk/"
SITEMAP_BEGIN = "  <!-- When will I use this? (written by scripts/build-uses.py from data/uses.json) -->\n"
SITEMAP_END = "  <!-- /When will I use this? -->\n"
GENERATED = "<!-- Generated by scripts/build-uses.py from data/uses.json. Do not edit: edit the data, then run the script. -->"
NOT_LIVE_SECTIONS = ("unlisted", "withdrawn")    # roster sections whose games are not live


def _load_module(name, rel):
    spec = importlib.util.spec_from_file_location(name, BASE / rel)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


cm = _load_module("check_meta", "scripts/check-meta.py")
cf = _load_module("check_footer", "scripts/check-footer.py")


def esc(s):
    """For an attribute value."""
    return html.escape(s, quote=True)


def txt(s):
    """For element text."""
    return html.escape(s, quote=False)


# ---------------------------------------------------------------- the data

def load(root):
    return json.loads((root / DATA).read_text(encoding="utf-8"))


def step_text(step):
    return step["text"] if isinstance(step, dict) else step


def live_games(root):
    """{slug: name} for every live game, in roster order: a numbered roster row outside the Unlisted and Withdrawn
    sections whose slug data/games.json lists."""
    listed = {g["slug"] for g in json.loads((root / GAMES).read_text(encoding="utf-8"))["games"]}
    out, live = {}, True
    for line in (root / ROSTER).read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            live = not line[3:].strip().lower().startswith(NOT_LIVE_SECTIONS)
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if live and len(c) >= 4 and c[0].isdigit():
            m = re.match(r"^`([a-z0-9-]+)`$", c[2])
            if m and m.group(1) in listed:
                out[m.group(1)] = c[1]
    return out


def practise(root, topic, live=None):
    """[(slug, name, description)] of the live games with a keyword in the topic's keywords, in roster order."""
    live = live_games(root) if live is None else live
    want = set(topic["keywords"])
    games = {g["slug"]: g for g in json.loads((root / GAMES).read_text(encoding="utf-8"))["games"]}
    return [(s, n, games[s]["description"]) for s, n in live.items() if want & set(games[s].get("keywords", []))]


def guide_name(root, slug):
    """The parent guide's own <h1>, as text."""
    m = re.search(r"<h1[^>]*>(.*?)</h1>", (root / "parents" / slug / "index.html").read_text(encoding="utf-8"), re.S)
    return html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else slug


# ---------------------------------------------------------------- maths in KaTeX, at display only

_NUM = r"£?(?:\d{1,3}(?: \d{3})+(?!\d)|\d+(?:\.\d+)?)%?"
_ATOM = r"\(*" + _NUM + r"(?:% of " + _NUM + r")?\)*"   # "3% of 230" is one term
_OP = r"(?: ?[+−×÷=] ?| : )"
MATH_RUN = re.compile(r"(?<![\w.£])" + _ATOM + r"(?:" + _OP + _ATOM + r")+(?![\w%])")
EXAMPLE = re.compile(r"\((example figures?)\)")


def _latex(run):
    s = re.sub(r"(\d) (?=\d{3}(?!\d))", r"\1\\,", run)   # 30 000 -> 30\,000
    s = s.replace("% of ", r"\% \text{ of } ")
    for a, b in (("×", r"\times "), ("÷", r"\div "), ("−", "-"), ("£", r"\pounds ")):
        s = s.replace(a, b)
    s = re.sub(r"(?<!\\)%", r"\%", s)
    return re.sub(r"  +", " ", s)


def prose(text):
    """Stored wording as HTML: maths runs set in KaTeX, "(example figure/s)" in italics, everything else escaped."""
    out, i = [], 0
    for m in MATH_RUN.finditer(text):
        out.append(_plain(text[i:m.start()]))
        out.append(r"\(" + txt(_latex(m.group(0))) + r"\)")
        i = m.end()
    out.append(_plain(text[i:]))
    return "".join(out)


def _plain(s):
    return EXAMPLE.sub(lambda m: "<em>(" + m.group(1) + ")</em>", txt(s))


# ---------------------------------------------------------------- pages

def url(path):
    return SITE + path[:-len("index.html")]


