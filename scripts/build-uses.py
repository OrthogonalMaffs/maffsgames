def colour_of(sc, colours):
    """A scenario's route colour; a scenario with no route takes the portal's navy."""
    return colours[sc["route"]] if sc["route"] else NO_ROUTE


def headline(sc):
    """The worked sum, after the steps on the job's own section (WWIUT-CARD-FORMAT): never on a hub card."""
    return '<p class="headline"><span class="answer-label">The answer:</span> %s</p>' % prose(sc["headline"])


def hook(sc, indent):
    """The formula (large, display style; none when null), its note if any, then the job's question."""
    out = []
    if sc["formula"] is not None:
        out.append(r'<p class="job-formula">\(\displaystyle %s\)</p>' % txt(sc["formula"]))
    if sc.get("formulaNote"):
        out.append('<p class="formula-note">%s</p>' % txt(sc["formulaNote"]))
    out.append('<p class="question">%s</p>' % txt(sc["question"]))
    return "".join(indent + x + "\n" for x in out)


def scenario_html(sc, routes, h, colours):
    """One scenario: the job, its route as a chip in the route's colour (or none), the formula, note and question, the
    wording, the numbered steps, then the headline sum as "The answer:". The card's top band is the route's colour."""
    out = ['<section id="%s" class="job" style="--c:%s">\n' % (esc(sc["id"]), colour_of(sc, colours)),
           "  <%s>%s</%s>\n" % (h, txt(sc["job"]), h)]
    chips = []
    if sc["route"]:
        chips.append('<a class="route-chip" href="/%s/route/%s/">%s</a>' % (SECTION, sc["route"], txt(routes[sc["route"]])))
    if sc["tier"] in TIER_TAG:
        chips.append('<span class="tier-tag">%s</span>' % TIER_TAG[sc["tier"]])
    if chips:
        out.append('  <p class="chip-row">%s</p>\n' % "".join(chips))
    out.append(hook(sc, "  "))
    if sc["exampleFigures"]:
        out.append('  <p class="practice-note">Uses example figures: the numbers marked <em>(example figure)</em> or '
                   '<em>(example figures)</em> are made up to show the method.</p>\n')
    out.append("  <p>%s</p>\n" % prose(sc["text"]))
    out.append('  <ol class="step-list">\n')
    out += ["    <li>%s</li>\n" % prose(step_text(s)) for s in sc["steps"]]
    out.append("  </ol>\n  %s\n</section>\n\n" % headline(sc))
    return "".join(out)


def sources_html(scenarios):
    out = ['<section>\n  <h2>Sources</h2>\n  <p>Every job and every figure that is not an example comes from a public page '
           'you can check.</p>\n  <ul>\n']
    for sc in scenarios:
        links = "; ".join('<a href="%s">%s</a>' % (esc(s["url"]), txt(s["title"])) for s in sc["sources"])
        out.append("    <li><strong>%s:</strong> %s</li>\n" % (txt(sc["job"]), links))
    out.append("  </ul>\n</section>\n\n")
    return "".join(out)


def topic_page(root, d, t, routes, colours, values, live):
    scs = [s for s in d["scenarios"] if s["topic"] == t["slug"]]
    body = [hero("When will I use this?", "%s: when will I use this?" % t["title"], t["answer"])]
    body += [scenario_html(s, routes, "h2", colours) for s in scs]
    games = practise(root, t, live)
    body.append('<section>\n  <h2>Practise it</h2>\n  <p>Games on MaffsGames that practise %s:</p>\n  <ul>\n'
                % txt(t["title"].lower()))
    body += ['    <li><a href="/games/%s/">%s</a>: %s</li>\n' % (s, txt(n), txt(desc)) for s, n, desc in games]
    body.append("  </ul>\n</section>\n\n")
    if t["parentGuide"]:
        body.append('<section>\n  <h2>Help at home</h2>\n  <p>For parents and carers: our guide to '
                    '<a href="/parents/%s/">%s</a>.</p>\n</section>\n\n' % (t["parentGuide"], txt(guide_name(root, t["parentGuide"]))))
    body.append(sources_html(scs))
    return head(values, True) + nav("/%s/" % SECTION, "When will I use this?") + "".join(body) + tail()


def route_page(d, r, topics, routes, colours, values):
    scs = [s for s in d["scenarios"] if s["route"] == r["slug"]]
    body = [hero("Maths at work", r["name"], "Jobs in this route, and the maths they use.", r["colour"])]
    for t in topics:
        group = [s for s in scs if s["topic"] == t["slug"]]
        if group:
            body.append('<h2 class="section-title"><a href="/%s/%s/">%s</a></h2>\n\n' % (SECTION, t["slug"], txt(t["title"])))
            body += [scenario_html(s, routes, "h3", colours) for s in group]
    body.append(sources_html([s for t in topics for s in scs if s["topic"] == t["slug"]]))
    return head(values, True) + nav("/%s/" % SECTION, "When will I use this?") + "".join(body) + tail()


