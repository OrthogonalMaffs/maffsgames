def live_games(root):
    """{slug: name} for every live game, in roster order: a numbered roster row outside the Unlisted and Withdrawn
    sections whose slug data/games.json lists."""
    listed = {g["slug"] for g in json.loads((root / GAMES).read_text(encoding="utf-8"))["games"]}
    out, live = {}, True
    for line in (root / ROSTER).read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            live = not line[3:].strip().lower().startswith(NOT_LIVE_SECTIONS)
            continue
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if live and len(c) >= 4 and c[0].isdigit():
            m = re.match(r"^`([a-z0-9-]+)`$", c[2])
            if m and m.group(1) in listed:
                out[m.group(1)] = c[1]
    return out


def practise(root, topic, live=None):
    """[(slug, name, description)] of the live games with a keyword in the topic's keywords, in roster order."""
    live = live_games(root) if live is None else live
    want = set(topic["keywords"])
    games = {g["slug"]: g for g in json.loads((root / GAMES).read_text(encoding="utf-8"))["games"]}
    return [(s, n, games[s]["description"]) for s, n in live.items() if want & set(games[s].get("keywords", []))]


def guide_name(root, slug):
    """The parent guide's own <h1>, as text."""
    m = re.search(r"<h1[^>]*>(.*?)</h1>", (root / "parents" / slug / "index.html").read_text(encoding="utf-8"), re.S)
    return html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else slug


# ---------------------------------------------------------------- maths in KaTeX, at display only

_SUP = "⁰¹²³⁴⁵⁶⁷⁸⁹"
_NUM = r"£?(?:\d{1,3}(?:,\d{3})+(?![\d,])(?:\.\d+)?|\d{1,3}(?: \d{3})+(?!\d)|\d+/\d+(?![\d./])|\d+(?:\.\d+)?|½)%?"
_PRE = r"(?:√|(?:sin|cos|tan)(?:⁻¹)? ?)*"   # √68, sin 10°, sin⁻¹(0.5)
_POST = r"[" + _SUP + r"]*°?"               # 2², 120°
_ATOM = r"\(*" + _PRE + r"\(*−?" + _NUM + _POST + r"(?:% of " + _NUM + r")?(?:\)[" + _SUP + r"]*)*"   # "3% of 230" is one term
_OP = r"(?: ?[+−×÷=] ?| : )"
MATH_RUN = re.compile(r"(?<![\w.£])" + _ATOM + r"(?:" + _OP + _ATOM + r")+(?![\w%])")
EXAMPLE = re.compile(r"\((example figures?)\)")


def _sqrt_latex(s):
    """√(x) -> \\sqrt{x}; √68 -> \\sqrt{68}."""
    while "√" in s:
        i = s.index("√")
        if s[i + 1:i + 2] == "(":
            depth, j = 0, i + 1
            while j < len(s):
                depth += {"(": 1, ")": -1}.get(s[j], 0)
                if depth == 0:
                    break
                j += 1
            s = s[:i] + r"\sqrt{" + s[i + 2:j] + "}" + s[j + 1:]
        else:
            m = re.match(r"[\d.]*", s[i + 1:])
            s = s[:i] + r"\sqrt{" + m.group(0) + "}" + s[i + 1 + len(m.group(0)):]
    return s


def _latex(run):
    s = re.sub(r"(\d) (?=\d{3}(?!\d))", r"\1\\,", run)   # 30 000 -> 30\,000
    s = re.sub(r"(\d),(?=\d{3})", r"\1{,}", s)           # 1,000 -> 1{,}000: no space after the comma
    s = _sqrt_latex(s)
    s = s.replace("⁻¹", "^{-1}")
    s = re.sub("[" + _SUP + "]+", lambda m: "^{" + "".join(str(_SUP.index(c)) for c in m.group(0)) + "}", s)
    s = re.sub(r"\b(sin|cos|tan)\b ?", lambda m: "\\" + m.group(1) + " ", s)
    s = s.replace("°", r"^\circ ").replace("½", r"\tfrac{1}{2}")
    s = s.replace("% of ", r"\% \text{ of } ")
    for a, b in (("×", r"\times "), ("÷", r"\div "), ("−", "-"), ("£", r"\pounds ")):
        s = s.replace(a, b)
    s = re.sub(r"(?<!\\)%", r"\%", s)
    return re.sub(r"  +", " ", s)


def prose(text):
    """Stored wording as HTML: maths runs set in KaTeX, "(example figure/s)" in italics, everything else escaped."""
    out, i = [], 0
    for m in MATH_RUN.finditer(text):
        out.append(_plain(text[i:m.start()]))
        out.append(r"\(" + txt(_latex(m.group(0))) + r"\)")
        i = m.end()
    out.append(_plain(text[i:]))
    return "".join(out)


def _plain(s):
    return EXAMPLE.sub(lambda m: "<em>(" + m.group(1) + ")</em>", txt(s))


