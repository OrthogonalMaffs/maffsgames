def lhs_value(lhs):
    """Exact value of a left side, BODMAS, leading zeros allowed; None if malformed or dividing by zero."""
    toks = re.findall(r'\d+|[+\-*/]', lhs)
    if ''.join(toks) != lhs or len(toks) % 2 == 0:
        return None
    for i, t in enumerate(toks):
        if (i % 2 == 0) != t.isdigit():
            return None
    terms, ops = [Fraction(int(toks[0]))], []
    i = 1
    while i < len(toks):
        op, n = toks[i], Fraction(int(toks[i + 1]))
        i += 2
        if op in '*/':
            if op == '/' and n == 0:
                return None
            terms[-1] = terms[-1] * n if op == '*' else terms[-1] / n
        else:
            ops.append(op)
            terms.append(n)
    r = terms[0]
    for op, v in zip(ops, terms[1:]):
        r = r + v if op == '+' else r - v
    return r


def equation_ok(eq):
    if len(eq) != N or eq.count('=') != 1:
        return False
    lhs, rhs = eq.split('=')
    if not rhs.isdigit():
        return False
    v = lhs_value(lhs)
    return v is not None and v.denominator == 1 and v == int(rhs) and int(rhs) > 0


def wordle(guess, target):
    res = ['absent'] * N
    left = {}
    for i in range(N):
        if guess[i] == target[i]:
            res[i] = 'correct'
        else:
            left[target[i]] = left.get(target[i], 0) + 1
    for i in range(N):
        if res[i] == 'correct':
            continue
        if left.get(guess[i], 0) > 0:
            res[i] = 'present'
            left[guess[i]] -= 1
    return res


def hard_ref(guesses, target, cand):
    for g in guesses:
        sts = wordle(g, target)
        for i in range(N):
            if sts[i] == 'correct' and cand[i] != g[i]:
                return 'Position %d must be "%s" (Hard Mode)' % (i + 1, g[i])
        for i in range(N):
            if sts[i] == 'present' and g[i] not in cand:
                return 'Must include "%s" (Hard Mode)' % g[i]
    return None


def daily_ref(y, m, d, size):
    n = (y * 10000 + m * 100 + d) * 1664525 + 1013904223
    n &= 0xffffffff
    return int((n / 0xffffffff) * size)


def strip_zeros(lhs):
    return re.sub(r'\d+', lambda m: str(int(m.group(0))), lhs)


def enumerate_valid():
    """Every valid 8-character equation with no '=' faults: numbers of 1-4 digits, 2 or 3 of them."""
    out = []
    for L in (4, 5, 6):
        rd = 7 - L
        top = 10 ** rd
        for k in (2, 3):
            for ws in itertools.product(range(1, 5), repeat=k):
                if sum(ws) + k - 1 != L:
                    continue
                for ops in itertools.product('+-*/', repeat=k - 1):
                    for nums in itertools.product(*[range(10 ** w) for w in ws]):
                        try:
                            if k == 2:
                                a, b = nums
                                v = a + b if ops[0] == '+' else a - b if ops[0] == '-' else a * b if ops[0] == '*' else a / b
                            else:
                                a, b, c = nums
                                o1, o2 = ops
                                if o1 in '*/':
                                    x = a * b if o1 == '*' else a / b
                                    v = x + c if o2 == '+' else x - c if o2 == '-' else x * c if o2 == '*' else x / c
                                elif o2 in '*/':
                                    y = b * c if o2 == '*' else b / c
                                    v = a + y if o1 == '+' else a - y
                                else:
                                    v = a + b + c if (o1, o2) == ('+', '+') else a + b - c if (o1, o2) == ('+', '-') else a - b + c if (o1, o2) == ('-', '+') else a - b - c
                        except ZeroDivisionError:
                            continue
                        r = round(v)
                        if abs(v - r) > 1e-6 or r < 1 or r >= top:
                            continue
                        lhs = ''
                        for i, n in enumerate(nums):
                            lhs += str(n).zfill(ws[i]) + (ops[i] if i < k - 1 else '')
                        eq = lhs + '=' + str(r).zfill(rd)
                        val = lhs_value(lhs)
                        if val is not None and val == r:
                            out.append(eq)
    return out


def check_bank(fails, bank):
    if len(set(bank)) != len(bank):
        fails.append('bank: %d entries but %d different' % (len(bank), len(set(bank))))
    pos = {}
    for e in bank:
        if not equation_ok(e):
            fails.append('bank: %s is not a true 8-character equation' % e)
            if len(fails) > 30:
                return
        i = e.find('=')
        pos[i] = pos.get(i, 0) + 1
    for p in pos:
        if p not in (4, 5, 6):
            fails.append('bank: "=" at index %s' % p)
    for ex in EXAMPLES:
        if not equation_ok(ex):
            fails.append('How to Play example %s is not a true equation' % ex)
        if ex not in set(bank):
            fails.append('How to Play example %s is not in the bank' % ex)


