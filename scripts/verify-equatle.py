"""Equatle: guess an 8-character true equation in 6 tries; the colours are Wordle's; BODMAS applies; leading zeros are legal.

The bank is generated by the page (`getBank()`, about 23,000 equations, no hardcoded list). The target is the bank entry
picked by the date (daily) or at random (free play). Marking is the colour of each tile.

Checks, independent of the game's code (every sum is `fractions.Fraction`; no float, no `eval`):
  Bank: every entry is 8 characters with one '='; the left side is numbers and operators alternating (leading zeros
    allowed), its value under BODMAS (multiply and divide first, left to right, then add and subtract) is exactly the
    right side, which is digits only and positive; no division by zero; no entry twice; '=' at index 4, 5 or 6. The five
    examples printed in How to Play are valid and in the bank.
  Acceptance: EVERY valid 8-character equation (numbers of 1 to 4 digits, any leading zeros, two or three numbers, any
    operators, exact value 1 or more that fits the right side) is enumerated here and `validate()` must accept it; the
    game's float evaluation must not turn a true equation into a refusal.
  Refusal: a wrong right side reads "<left side, leading zeros dropped> = <exact value>, not <right side>" with the
    figures worked out here; the malformed shapes (length, no or two '=', an empty side, letters or an operator on the
    right, doubled or leading or trailing operators, division by zero) are all refused.
  Colours: `states(guess, target)` equals the Wordle rule written here (greens first, then yellows from what the target has
    left) over every pair of 256 strings on {1,+} and 256 on {1,2}, and 10,000 pairs from the bank.
  Hard Mode: `checkHard()` refuses exactly when a green is not reused in place or a yellow character is missing, over
    3,000 random cases, with the position and character in the message.
  Daily pick: for 34 dates (month ends, a leap day, a year end) the target is the bank entry at floor(r * size) where r is
    the first draw of the generator seeded yyyymmdd; recomputed here.
  Play, in Chromium (390x844), on the page's own keyboard (key presses and the on-screen keys), with the page's timers stepped
    on a controlled clock: a 1-guess win; six wrong guesses (every tile and every keyboard key checked against the rule here,
    the equation revealed, then Next and the results); an invalid guess is refused with its message and costs no row; Hard Mode
    refuses a guess that drops a green; the on-screen keys are the 17 characters, labelled ×, ÷ and − for * / -.
No analytics or leaderboard request leaves the stub server (every other request is aborted).

Not asserted (open findings, left open): a result of 0 is refused without saying so (equatle-t2-001, a ruling for Jon) and
the puzzle number's UTC/BST off-by-one (equatle-t2-002).

    python scripts/verify-equatle.py [--no-selftest] [--against FILE]
"""
