def key_label(k):
    return {'*': '×', '/': '÷', '-': '−'}.get(k, k)


def kbd_ref(guesses, target):
    order = ['correct', 'present', 'absent']
    m = {}
    for g in guesses:
        for ch, s in zip(g, wordle(g, target)):
            if ch not in m or order.index(s) < order.index(m[ch]):
                m[ch] = s
    return m


def type_guess(page, s):
    for ch in s:
        page.keyboard.press(ch)


def tiles(page, row):
    return page.evaluate('(r) => [...Array(8).keys()].map(c => document.getElementById("t" + r + c).dataset.s || "")', row)


def play_checks(fails, page, bank):
    # an on-screen keyboard: the 17 characters, labelled as the maths is written
    keys = page.evaluate('() => [...document.querySelectorAll(".key[data-k]")].map(b => [b.dataset.k, b.textContent.trim()])')
    want = sorted((c, key_label(c)) for c in '0123456789+-*/=')
    if sorted(map(tuple, keys)) != want:
        fails.append('keyboard: keys %r, expected %r' % (sorted(map(tuple, keys)), want))
    target = page.evaluate('() => G.target')
    if target not in set(bank):
        fails.append('play: the target %r is not a bank equation' % target)
    # an invalid guess is refused with its reason and costs no row
    for bad, want_msg in (('1+1=3000', '1+1 = 2, not 3000'), ('12345678', 'Must contain ='), ('1+2=3=00', 'Only one = allowed')):
        type_guess(page, bad)
        page.keyboard.press('Enter')
        msg = page.evaluate('() => document.getElementById("msg").textContent')
        rows = page.evaluate('() => G.guesses.length')
        if rows != 0 or msg != want_msg:
            fails.append('play: refusing %r: message %r, rows used %d, expected %r' % (bad, msg, rows, want_msg))
        for _ in range(8):
            page.keyboard.press('Backspace')
    # six wrong guesses, each tile and each key checked against the rule here
    rng = random.Random(7)
    pool = [e for e in bank if e != target]
    # make the guesses share characters with the target so every colour appears
    scored = sorted(pool, key=lambda e: -sum(1 for a, b in zip(e, target) if a == b or a in target))
    same_rhs = [e for e in pool if e.split('=')[1] == target.split('=')[1]]
    guesses = [same_rhs[0] if same_rhs else scored[0], rng.choice(pool), scored[len(scored) // 3], rng.choice(pool),
               scored[len(scored) // 2], rng.choice(pool)]
    seen = []
    for r, g in enumerate(guesses):
        type_guess(page, g)
        page.keyboard.press('Enter')
        page.clock.run_for(3000)
        seen.append(g)
        got = tiles(page, r)
        if got != wordle(g, target):
            fails.append('play: row %d %s against %s: tiles %r, rule says %r' % (r + 1, g, target, got, wordle(g, target)))
        km = kbd_ref(seen, target)
        kk = page.evaluate('() => Object.fromEntries([...document.querySelectorAll(".key[data-k]")].map(b => [b.dataset.k, b.dataset.s || ""]))')
        for ch, s in kk.items():
            if s != km.get(ch, ''):
                fails.append('play: after row %d the key %r is %r, rule says %r' % (r + 1, ch, s, km.get(ch, '')))
                break
    if not same_rhs:
        fails.append('play: no other bank equation has the target\'s right side (%s), so the right-side-only fault cannot be tried' % target)
    st = page.evaluate('() => ({status: G.status, msg: document.getElementById("msg").textContent, next: !!document.querySelector("#nextMount button, #nextMount .next-btn, #nextMount *")})')
    if st['status'] != 'lost' or st['msg'] != 'The equation was ' + ''.join({'*': '×', '/': '÷'}.get(c, c) for c in target):
        fails.append('play: after six misses the status is %r and the message %r' % (st['status'], st['msg']))
    if not st['next']:
        fails.append('play: no Next control after a lost puzzle')


def win_checks(fails, page, bank):
    target = page.evaluate('() => G.target')
    type_guess(page, target)
    page.keyboard.press('Enter')
    page.clock.run_for(4000)
    t = tiles(page, 0)
    if t != ['correct'] * N:
        fails.append('win: the target typed in reads %r' % t)
    info = page.evaluate('() => ({status: G.status, n: G.guesses.length, esub: document.getElementById("esub").textContent, open: !document.getElementById("m-end").classList.contains("hidden"), stats: JSON.parse(localStorage.getItem("eq_stats") || "{}")})')
    if info['status'] != 'won' or info['n'] != 1 or not info['esub'].startswith('Solved in 1/6') or not info['open']:
        fails.append('win: after a 1-guess win: %r' % info)
    s = info['stats']
    if s.get('played') != 1 or s.get('won') != 1 or s.get('dist', [0])[0] != 1 or s.get('streak') != 1:
        fails.append('win: the stats after one win are %r' % s)


def hard_play_checks(fails, page, bank):
    target = page.evaluate('() => G.target')
    pool = [e for e in bank if e != target]
    # a guess with at least one green and one other character
    g = next(e for e in pool if sum(1 for a, b in zip(e, target) if a == b) >= 1)
    type_guess(page, g)
    page.keyboard.press('Enter')
    page.clock.run_for(3000)
    sts = wordle(g, target)
    gi = sts.index('correct')
    # a second guess that changes the green's place
    cand = next(e for e in pool if e[gi] != g[gi] and hard_ref([g], target, e) is not None and hard_ref([g], target, e).startswith('Position'))
    type_guess(page, cand)
    page.keyboard.press('Enter')
    msg = page.evaluate('() => document.getElementById("msg").textContent')
    want = hard_ref([g], target, cand)
    rows = page.evaluate('() => G.guesses.length')
    if msg != want or rows != 1:
        fails.append('hard: dropping a green reads %r (rows %d), expected %r' % (msg, rows, want))


def play(fails, html):
    from playwright.sync_api import sync_playwright
    proc, base = bc.start_stub_server()
    stats = {}
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch()
            page_url = re.compile(r'/games/%s/(\?[^/]*)?$' % SLUG)

            def new_page(prefs=None):
                ctx = browser.new_context(viewport={'width': 390, 'height': 844})
                ctx.add_init_script(bc.NO_LOCK_FRESH_INIT)
                if prefs:
                    ctx.add_init_script("try{localStorage.setItem('eq_prefs','%s')}catch(e){}" % prefs)
                ctx.route(lambda url: not url.startswith(base), lambda route: route.abort())
                ctx.route(lambda url: bool(page_url.search(url)), lambda route: route.fulfill(
                    status=200, content_type='text/html; charset=utf-8', body=html))
                pg = ctx.new_page()
                errors = []
                pg.on('pageerror', lambda e: errors.append(str(e)))
                pg.clock.install(time=datetime(2026, 10, 12, 10, 0, 0))
                pg.goto(base + '/games/%s/?cb=verify' % SLUG, wait_until='load', timeout=20000)
                pg.wait_for_function('typeof getBank === "function" && !!document.getElementById("t00")', timeout=15000)
                return pg, errors

            page, errors = new_page()
            bank = page.evaluate('() => getBank().slice()')
            check_bank(fails, bank)
            # acceptance of every valid equation
            valid = enumerate_valid()
            bad = []
            for i in range(0, len(valid), 20000):
                chunk = valid[i:i + 20000]
                for e, r in zip(chunk, page.evaluate(VALIDATE_JS, chunk)):
                    if r is not None:
                        bad.append((e, r))
            for e, r in bad[:8]:
                fails.append('acceptance: the true equation %s is refused (%r)' % (e, r))
            if len(bad) > 8:
                fails.append('acceptance: %d true equations refused in all' % len(bad))
            # refusal, with the right figures
            rng = random.Random(11)
            sample = rng.sample(valid, 400)
            msgs = page.evaluate(VALIDATE_JS, [e.split('=')[0] + '=' + str(int(e.split('=')[1]) + 1).zfill(len(e.split('=')[1])) for e in sample])
            for e, m in zip(sample, msgs):
                lhs, rhs = e.split('=')
                bad_rhs = str(int(rhs) + 1).zfill(len(rhs))
                if len(bad_rhs) != len(rhs):
                    continue
                want = '%s = %d, not %d' % (strip_zeros(lhs), int(lhs_value(lhs)), int(bad_rhs))
                if m != want:
                    fails.append('refusal: %s=%s reads %r, expected %r' % (lhs, bad_rhs, m, want))
                    break
            malformed = ['1+1=3', '1+1=2000', 'abc=defg', '1+2+3+4=10', '1+2=3=00', '=1234567', '1234567=', '1+2+3=1+', '1++2=003',
                         '+1+2+3=7', '1+2+3+=07', '9/0+1=10', '9/00+1=1', '5-9+3=-1', '1+2+3=0a']
            for m, r in zip(malformed, page.evaluate(VALIDATE_JS, malformed)):
                if r is None:
                    fails.append('refusal: the malformed %r is accepted' % m)
            # colours
            for alpha in ('1+', '12'):
                strs = [''.join(p) for p in itertools.product(alpha, repeat=N)]
                got = page.evaluate(STATES_JS, [strs, strs])
                for gi, g in enumerate(strs):
                    for ti, t in enumerate(strs):
                        want = ''.join(s[0] for s in wordle(g, t))
                        if got[gi][ti] != want:
                            fails.append('colours: guess %s against %s reads %s, the Wordle rule gives %s' % (g, t, got[gi][ti], want))
                            break
                    else:
                        continue
                    break
            rng = random.Random(5)
            targets = rng.sample(bank, 100)
            guesses = rng.sample(bank, 100)
            got = page.evaluate(STATES_JS, [guesses, targets])
            for gi, g in enumerate(guesses):
                for ti, t in enumerate(targets):
                    want = ''.join(s[0] for s in wordle(g, t))
                    if got[gi][ti] != want:
                        fails.append('colours: bank guess %s against %s reads %s, expected %s' % (g, t, got[gi][ti], want))
                        break
            # hard mode
            cases = []
            for _ in range(3000):
                t = rng.choice(bank)
                prev = [rng.choice(bank) for _ in range(rng.randint(1, 3))]
                c = rng.choice(bank) if rng.random() < 0.6 else t
                cases.append([prev, t, c])
            got = page.evaluate(HARD_JS, cases)
            for (prev, t, c), r in zip(cases, got):
                want = hard_ref(prev, t, c)
                if r != want:
                    fails.append('hard: guesses %r, target %s, candidate %s: reads %r, expected %r' % (prev, t, c, r, want))
                    break
            # daily pick
            picks = page.evaluate(DAILY_JS, [list(d) for d in DATES])
            for d, p in zip(DATES, picks):
                want = bank[daily_ref(d[0], d[1], d[2], len(bank))]
                if p != want:
                    fails.append('daily: %04d-%02d-%02d picks %s, expected %s' % (d[0], d[1], d[2], p, want))
                    break
            if errors:
                fails.append('page errors: %s' % '; '.join(errors[:3]))
            page1, errors1 = new_page()
            play_checks(fails, page1, bank)
            if errors1:
                fails.append('page errors (play): %s' % '; '.join(errors1[:3]))
            page2, errors2 = new_page()
            win_checks(fails, page2, bank)
            if errors2:
                fails.append('page errors (win): %s' % '; '.join(errors2[:3]))
            page3, errors3 = new_page('{"hard":true,"free":false,"cb":false}')
            hard_play_checks(fails, page3, bank)
            browser.close()
            stats = {'bank': len(bank), 'valid': len(valid)}
    finally:
        proc.terminate()
        proc.wait()
    return stats


