    sys.stdout.reconfigure(encoding='utf-8')
    html = open(args.against or GAME, encoding='utf-8').read()
    fails = []
    st = play(fails, html)
    print('%s: %d bank equations recomputed exactly; %d valid 8-character equations enumerated and all accepted; colours checked over '
          '131,000+ pairs, Hard Mode over 3,000 cases, the daily pick over %d dates; played in Chromium' % (
              SLUG, st.get('bank', 0), st.get('valid', 0), len(DATES)))
    print('  not asserted (open): a result of 0 refused (equatle-t2-001, for Jon) and the puzzle number off-by-one (equatle-t2-002)')
    ok = True
    if not args.no_selftest and not args.against:
        for what, tag, edits in PLANTS:
            bad = [o for o, n in edits if html.count(o) != 1]
            if bad:
                print('  self-test %-58s *** CANNOT PLANT (%r) ***' % (what, bad[0][:60]))
                ok = False
                continue
            planted = html
            for o, n in edits:
                planted = planted.replace(o, n)
