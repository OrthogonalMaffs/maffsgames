# ---------------------------------------------------------------- polynomials of our own: {degree: coefficient}
def p_add(a, b, sign=1):
    r = dict(a)
    for d, c in b.items():
        r[d] = r.get(d, 0) + sign * c
    return {d: c for d, c in r.items() if c}


def p_mul(a, b):
    r = {}
    for d1, c1 in a.items():
        for d2, c2 in b.items():
            r[d1 + d2] = r.get(d1 + d2, 0) + c1 * c2
    return {d: c for d, c in r.items() if c}


def vec(p):          # {2: c2, 1: c1, 0: c0} -> [c2, c1, c0]
    return [p.get(2, 0), p.get(1, 0), p.get(0, 0)]


def parse_poly(s):
    """A polynomial written as the game prints it: 7(x + 9), -7(x - 5), x(x + 9), 4x(2x - 3), (x + 3)(x - 5), 15x^2 + 21x."""
    toks = re.findall(r'\d+|x|\^|\+|-|\(|\)', s.replace(' ', ''))
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def nxt():
        t = toks[pos[0]]
        pos[0] += 1
        return t

    def factor():
        t = nxt()
        if t == '(':
            e = expr()
            assert nxt() == ')'
            return e
        if t == 'x':
            if peek() == '^':
                nxt()
                return {int(nxt()): 1}
            return {1: 1}
        return {0: int(t)}

    def term():
        neg = False
        if peek() == '-':
            nxt()
            neg = True
        r = factor()
        while peek() and (peek() == 'x' or peek() == '(' or peek().isdigit()):
            r = p_mul(r, factor())
        return {d: -c for d, c in r.items()} if neg else r

    def expr():
        r = term()
        while peek() in ('+', '-'):
            op = nxt()
            r = p_add(r, term(), 1 if op == '+' else -1)
        return r

    out = expr()
    assert pos[0] == len(toks), 'could not read all of ' + s
    return out


def tex_blocks(text):
    return text.split('§')[1::2]


def form_poly(form, v):     # what the typed numbers multiply out to, written here again
    if form in ('lin2', 'lin2neg'):
        return [0, v[0], v[1]]
    if form == 'quad3':
        return [v[0], v[1], v[2]]
    if form == 'quad3lead1':
        return [1, v[0], v[1]]
    if form == 'hcfnum':
        return vec(p_mul({0: v[0]}, {1: v[1], 0: v[2]}))
    if form == 'hcfx':
        return vec(p_mul({1: v[0]}, {1: v[1], 0: v[2]}))
    if form == 'brackets':
        return vec(p_mul({1: 1, 0: v[0]}, {1: 1, 0: v[1]}))
    raise AssertionError(form)


def shape_of(layout):
    s = ''
    for tk in layout:
        s += tk['lit'] if 'lit' in tk else ('±□' if tk['sign'] else '□')
    return s


def solve_roots(b, c):      # integer p, q with p + q = b and p q = c, if any (brute force)
    for p in range(-81, 82):
        if p and c % p == 0 and p + c // p == b:
            return p, c // p
    return None


def signs_expected(b, c):
    """The sign grid, from the roots themselves: 0 both +, 1 both -, 2 one of each."""
    r = solve_roots(b, c)
    if r is None:
        return None
    p, q = r
    return 0 if p > 0 and q > 0 else 1 if p < 0 and q < 0 else 2


# ---------------------------------------------------------------- what each question must be, from its printed stem
def question_poly(q):
    """The printed polynomial of a question: the expression to expand, the polynomial to factorise, or the quadratic."""
    blocks = tex_blocks(q['stem'])
    return parse_poly(blocks[-1]), blocks[-1]


def expected_target(q):
    p, _ = question_poly(q)
    if q['stage'] in (1, 2, 4):
        return vec(p)
    if q['stage'] == 3:
        return vec(p)
    return vec(p)


def expected_slips(q, tgt):
    """The contract's named slips for this question, as polynomials, from the printed expression alone."""
    st, sub = q['stage'], q['sub']
    c2, c1, c0 = tgt
    if st == 1:
        return [[0, c1, c0 // c1]]                          # kx + a: multiplied the first term only
    if st == 2 and sub == 'neg':
        return [[0, c1, -c0]]                               # the sign of the second term
    if st == 2 and sub == 'xout':
        return [[1, 0, c1]]                                 # x^2 + a
    if st == 2:
        return [[c2, c1 // c2, 0]]                          # kx^2 + a x
    if st == 4:
        return [[1, 0, c0], [1, c1, c1]]                    # missing middle term; (a + b) in place of ab
    if st == 6:
        return [[1, -c1, c0], [1, c1, -c0]]                 # multiply to c but add to -b; add to b but multiply to -c
    return []


def gcd_all(*xs):
    g = 0
    for x in xs:
        g = math.gcd(g, abs(x))
    return g


def canon_vector(tgt):
    c2, c1, c0 = tgt
    if c2 == 0:
        g = gcd_all(c1, c0)
        return [g, c1 // g, c0 // g], 'hcfnum'
    g = gcd_all(c2, c1)
    return [g, c2 // g, c1 // g], 'hcfx'


# ---------------------------------------------------------------- one question's findings
def check_question(q):
    errs = []
    st, sub = q['stage'], q['sub']
    try:
        poly, printed = question_poly(q)
    except (AssertionError, IndexError, KeyError, ValueError) as e:
        return ['stem %r could not be read: %s' % (q.get('stem'), e)]
    tgt = vec(poly)
    tag = '%s' % printed
    if q['marks'] != MARKS[st] or len(q['steps']) != MARKS[st]:
        errs.append('%s: %d marks in %d steps, the stage has %d' % (tag, q['marks'], len(q['steps']), MARKS[st]))
    if not q['worked']['lines'] or len(q['worked']['lines']) < 2 or any(not l for l in q['worked']['lines']):
        errs.append('%s: no worked answer' % tag)
    box = [s for s in q['steps'] if s['kind'] == 'boxes']
    signs = [s for s in q['steps'] if s['kind'] == 'signs']

    if st in (1, 2, 3, 4):
        if len(box) != 1 or signs:
            return errs + ['%s: stage %d should be one box step' % (tag, st)]
        s = box[0]
        want_form = {1: 'lin2', 4: 'quad3lead1', 3: 'hcfnum' if tgt[0] == 0 else 'hcfx'}.get(st)
        if st == 2:
            want_form = 'lin2neg' if sub == 'neg' else 'quad3'
        if s['form'] != want_form:
            errs.append('%s: form %s, expected %s' % (tag, s['form'], want_form))
        if st in (1, 2, 4):                                  # an expansion: the printed expression multiplied out
            want = tgt
        else:                                                # a factorisation: the printed polynomial itself
            want = tgt
        if s['target'] != want:
            errs.append('%s: target %s but the printed expression multiplies out to %s' % (tag, s['target'], want))
        if form_poly(s['form'], s['sol']) != want:
            errs.append('%s: the solution %s multiplies out to %s, not %s' % (tag, s['sol'], form_poly(s['form'], s['sol']), want))
        if st == 1:
            k = tgt[1]
            if not (2 <= k <= 9 and tgt[2] % k == 0 and 1 <= abs(tgt[2] // k) <= 9 and tgt[0] == 0):
                errs.append('%s: outside k 2-9, a +-1-9' % tag)
        if st == 4:
            if tgt[0] != 1 or printed.count('(') != 2:
                errs.append('%s: not (x + a)(x + b)' % tag)
        if st == 3:
            cv, form = canon_vector(tgt)
            if s.get('canon') != cv or s['form'] != form:
                errs.append('%s: canonical answer %s (%s) is not the fully factorised %s (%s)' % (tag, s.get('canon'), s['form'], cv, form))
            if s.get('canon') and form_poly(s['form'], s['canon']) != tgt:
                errs.append('%s: the canonical answer multiplies out to %s' % (tag, form_poly(s['form'], s['canon'])))
            if s.get('canon') and (s['canon'][0] < 1 or gcd_all(s['canon'][1], s['canon'][2]) != 1):
                errs.append('%s: not fully factorised: %s' % (tag, s.get('canon')))
            if tgt[0] != 0 and tgt[2] != 0:
                errs.append('%s: a quadratic with a number term in stage 3' % tag)
    else:
        b, c = tgt[1], tgt[2]
        if tgt[0] != 1 or b == 0 or c == 0:
            errs.append('%s: not x^2 + bx + c with b and c non-zero' % tag)
        want = signs_expected(b, c)
        if want is None:
            errs.append('%s: does not factorise over the integers' % tag)
        if not signs:
            return errs + ['%s: no sign-grid step' % tag]
        g = signs[0]
        if q['steps'][0]['kind'] != 'signs':
            errs.append('%s: the signs are not asked first' % tag)
        if want is not None and g['correct'] != want:
            errs.append('%s: sign grid marked %d but b = %d, c = %d gives %d' % (tag, g['correct'], b, c, want))
        rule = 2 if c < 0 else (0 if b > 0 else 1)
        if g['correct'] != rule:
            errs.append('%s: the sign rule (c negative: different; c positive: the sign of b) gives %d, marked %d' % (tag, rule, g['correct']))
        txt = ' '.join(g['whys']) + ' ' + g['rule']
        if g['correct'] == 2 and 'different' not in g['rule']:
            errs.append('%s: the feedback does not state the rule (different signs for c negative)' % tag)
        if g['correct'] != 2 and 'same' not in g['rule']:
            errs.append('%s: the feedback does not state the rule (same signs for c positive)' % tag)
        if any(not w for i, w in enumerate(g['whys'])):
            errs.append('%s: an option has no line' % tag)
        named_want = [(c < 0 and o in (0, 1)) or (c > 0 and b < 0 and o == 0 and g['correct'] == 1) for o in range(3)]
        if g['named'] != named_want:
            errs.append('%s: named slips %s, the contract names %s' % (tag, g['named'], named_want))
        if not any('multiply to' in l and 'add to' in l for l in q['worked']['lines']):
            errs.append('%s: the worked lines do not say "two numbers that multiply to c and add to b"' % tag)
        if not any(('same signs' in l or 'signs are the same' in l) if c > 0 else ('different' in l) for l in q['worked']['lines']):
            errs.append('%s: the worked lines do not show the sign grid' % tag)
        if st == 6:
            if len(box) != 1 or box[0]['form'] != 'brackets':
                errs.append('%s: stage 6 needs the bracket boxes' % tag)
            else:
                s = box[0]
                if s['target'] != tgt:
                    errs.append('%s: target %s, printed %s' % (tag, s['target'], tgt))
                if form_poly('brackets', s['sol']) != tgt:
                    errs.append('%s: the solution %s multiplies out to %s' % (tag, s['sol'], form_poly('brackets', s['sol'])))
        elif box:
            errs.append('%s: stage 5 asks only for the signs' % tag)

    for s in box:
        if shape_of(s['layout']) != SHAPES[s['form']]:
            errs.append('%s: layout %s is not the bracket shape %s' % (tag, shape_of(s['layout']), SHAPES[s['form']]))
        seen = [tuple(tgt)]
        for sl in s['slips']:
            if tuple(sl['poly']) in seen:
                errs.append('%s: a slip has the value of the answer or of another slip: %s' % (tag, sl['poly']))
            seen.append(tuple(sl['poly']))
            if not sl['why'] or len(sl['why']) > 260:
                errs.append('%s: a slip line is missing or long' % tag)
        want_slips = [sl for sl in expected_slips(q, tgt) if sl != tgt]
        have = [sl['poly'] for sl in s['slips']]
        for w in want_slips:
            if w not in have:
                errs.append('%s: the contract slip %s is not named' % (tag, w))
        if st == 4 and 'grid' not in q['worked']:
            errs.append('%s: no grid' % tag)
    if st == 4:
        g = q['worked'].get('grid')
        if not g:
            errs.append('%s: stage 4 is worked by the grid method; there is no grid' % tag)
        else:
            try:
                cols = [parse_poly(c) for c in g['cols']]
                rows = [parse_poly(r) for r in g['rows']]
                cells = [[parse_poly(c) for c in r] for r in g['cells']]
                for i in range(2):
                    for j in range(2):
                        if cells[i][j] != p_mul(rows[i], cols[j]):
                            errs.append('%s: grid cell %d,%d is wrong' % (tag, i, j))
                total = {}
                for r in cells:
                    for c in r:
                        total = p_add(total, c)
                if vec(total) != tgt:
                    errs.append('%s: the grid cells add to %s, not %s' % (tag, vec(total), tgt))
            except (AssertionError, KeyError, IndexError, ValueError) as e:
                errs.append('%s: the grid could not be read: %s' % (tag, e))
    return errs


# ---------------------------------------------------------------- the independent marker and its probes
def py_mark(q, si, v):
    step = q['steps'][si]
    poly, _ = question_poly(q)
    tgt = vec(poly)
    if step['kind'] == 'signs':
        b, c = tgt[1], tgt[2]
        right = signs_expected(b, c)
        if v == right:
            return 'right'
        if c < 0 and v in (0, 1):
            return 'slip'
        if c > 0 and b < 0 and v == 0:
            return 'slip'
        return 'wrong'
    got = form_poly(step['form'], v)
    if got == tgt:
        if q['stage'] == 3:
            cv, _ = canon_vector(tgt)
            if v != cv:
                return 'format'
        return 'right'
    slips = [sl for sl in expected_slips(q, tgt) if sl != tgt]
    # stage 3 slips are vectors: divide the x term but not the number term
    if q['stage'] == 3:
        cv, form = canon_vector(tgt)
        slips = [form_poly(form, [cv[0], cv[1], cv[0] * cv[2]])]
        slips = [sl for sl in slips if sl != tgt]
    return 'slip' if got in slips else 'wrong'


def probes_for(q, si, rng):
    step = q['steps'][si]
    if step['kind'] == 'signs':
        return [0, 1, 2]
    sol = step['sol']
    signed = [tk['sign'] for tk in step['layout'] if 'num' in tk]
    out = [list(sol)]
    n = len(sol)

    def ok(v):
        return all(signed[i] or v[i] >= 0 for i in range(n)) and all(abs(x) <= 99 for x in v)
    for i in range(n):
        for d in (-2, -1, 1, 2, 7):
            v = list(sol)
            v[i] += d
            out.append(v)
        v = list(sol)
        v[i] = 0
        out.append(v)
        v = list(sol)
        v[i] = -v[i]
        out.append(v)
    for i in range(n):
        for j in range(i + 1, n):
            v = list(sol)
            v[i], v[j] = v[j], v[i]
            out.append(v)
    out.append(list(reversed(sol)))
    out.append([-x for x in sol])
    poly, _ = question_poly(q)
    tgt = vec(poly)
    for sl in expected_slips(q, tgt):               # a vector for each slip, where the form lets us write one
        if step['form'] in ('lin2', 'lin2neg', 'quad3lead1'):
            out.append([sl[1], sl[2]])
        elif step['form'] == 'quad3':
            out.append(list(sl))
        elif step['form'] == 'brackets':
            out.append([-x for x in sol])
    if q['stage'] == 3:
        g, m, nn = step['canon']
        out.append([g, m, g * nn])                   # the named slip
        for d in range(2, g + 1):                    # every partial factorisation, still equal in value
            if g % d == 0:
                out.append([g // d, m * d, nn * d])
        out.append([1, g * m, g * nn])
    for _ in range(15):
        out.append([rng.randint(-9, 9) for _ in range(n)])
    out = [v for v in out if ok(v)]
    uniq = []
    for v in out:
        if v not in uniq:
            uniq.append(v)
    return uniq


