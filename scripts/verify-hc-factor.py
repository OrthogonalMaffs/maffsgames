# ---------------------------------------------------------------- the page and module under Playwright
def open_page(pw, base, html, module, size):
    br = pw.chromium.launch()
    touch = size[0] <= 600
    ctx = br.new_context(viewport={'width': size[0], 'height': size[1]}, has_touch=touch, is_mobile=touch)
    ctx.add_init_script(bc.NO_LOCK_FRESH_INIT)
    ctx.add_init_script(bc.NO_NEXT_FLOOR_INIT)
    page_url = re.compile(r'/games/%s/(\?[^/]*)?$' % SLUG)
    ctx.route(lambda url: not url.startswith(base), lambda route: route.abort())
    ctx.route(lambda url: bool(page_url.search(url)), lambda route: route.fulfill(
        status=200, content_type='text/html; charset=utf-8', body=html))
    ctx.route(lambda url: url.split('?')[0].endswith('/hc-factor-gen.js'), lambda route: route.fulfill(
        status=200, content_type='application/javascript; charset=utf-8', body=module))
    page = ctx.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(base + '/games/%s/?cb=verify' % SLUG, wait_until='load', timeout=20000)
    page.wait_for_function('!!window.HCF && !!HCF.ui', timeout=10000)
    page.evaluate("""() => { window.__ev = []; window.__sub = [];
        window.mfg = (n, p) => { window.__ev.push([n, p]); };
        window.MaffsLeaderboard = window.MaffsLeaderboard || {};
        MaffsLeaderboard.submitScore = (g, l, s, n) => { window.__sub.push([g, l, s, n]); return Promise.resolve(); }; }""")
    return br, page, errors


def check_engine(page, out, rng_seed=7):
    data = page.evaluate(GEN_JS)
    info = {}
    rng = random.Random(rng_seed)
    for st in range(1, 7):
        d = data[str(st)]
        bank = d['bank']
        keys = {q['key'] for q in bank}
        stems = {q['stem'] for q in bank}
        info[st] = len(keys)
        if len(keys) < MIN_DISTINCT or len(stems) < MIN_DISTINCT:
            out.append('stage %d: only %d distinct questions (need %d)' % (st, min(len(keys), len(stems)), MIN_DISTINCT))
        if not d['again']:
            out.append('stage %d: the bank is not the same on every load (fixed seed)' % st)
        if any(q['stage'] != st for q in bank):
            out.append('stage %d: a question of another stage' % st)
        bad = 0
        for i, q in enumerate(bank):
            for e in check_question(q):
                bad += 1
                if bad <= 6:
                    out.append('stage %d #%d: %s' % (st, i, e))
        if bad > 6:
            out.append('stage %d: ... and %d more findings' % (st, bad - 6))
        subs = {q['sub'] for q in bank}
        for sess in d['sessions']:
            if len(sess) != 6 or len(set(sess)) != 6:
                out.append('stage %d: a session of %d questions, %d distinct' % (st, len(sess), len(set(sess))))
                break
        if st in (2, 3) and not all(any(k.split(':')[0] == s for k in d['sessions'][0]) or True for s in subs):
            pass
        for sess in d['sessions']:
            kinds = {k.split(':')[0] for k in sess}
            if len(kinds) < min(len(subs), 2):
                out.append('stage %d: a session of one kind only: %s' % (st, sorted(kinds)))
                break
        # the module's marker against ours
        items, want = [], []
        for qi, q in enumerate(bank):
            for si in range(len(q['steps'])):
                for v in probes_for(q, si, rng):
                    items.append([st, qi, si, v])
                    want.append(py_mark(q, si, v))
        got = page.evaluate(PROBE_JS, items)
        wrong = [(items[i], want[i], got[i]) for i in range(len(items)) if want[i] != got[i]]
        for (it, w, g) in wrong[:4]:
            out.append('stage %d: mark() said %s for %s of %s, an independent marker says %s' % (st, g, it[3], bank[it[1]]['stem'], w))
        if len(wrong) > 4:
            out.append('stage %d: ... and %d more marking differences' % (st, len(wrong) - 4))
        info['probes%d' % st] = len(items)
        if st == 3:
            partial = [1 for (it, w, g) in zip(items, want, got) if w == 'format' and g == 'format']
            if not partial:
                out.append('stage 3: no partial factorisation was probed')
        if st == 6:
            swaps = 0
            for qi, q in enumerate(bank):
                sol = q['steps'][1]['sol']
                if sol[0] != sol[1]:
                    swaps += 1
            if not swaps:
                out.append('stage 6: no question with two different brackets to swap')
    return info


