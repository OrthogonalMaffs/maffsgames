# ---------------------------------------------------------------- our own expression parser (Fractions)
def evaluate(expr, vals):
    t = expr.split(' ')
    pos = [0]

    def peek():
        return t[pos[0]] if pos[0] < len(t) else None

    def take():
        pos[0] += 1
        return t[pos[0] - 1]

    def atom():
        k = take()
        if k == '(':
            v = total()
            assert take() == ')'
            return v
        if k.startswith('@'):
            return vals[k[1:]]
        v = Fraction(k)
        if peek() == '%':
            take()
            v = v / 100
        return v

    def power():
        b = atom()
        if peek() == '^':
            take()
            e = power()
            assert e.denominator == 1
            return b ** int(e)
        return b

    def prod():
        v = power()
        while peek() in ('*', '/'):
            op = take()
            r = power()
            v = v * r if op == '*' else v / r
        return v

    def total():
        v = prod()
        while peek() in ('+', '-'):
            op = take()
            r = prod()
            v = v + r if op == '+' else v - r
        return v

    out = total()
    assert pos[0] == len(t), 'trailing tokens'
    return out


def refs(expr):
    return [k[1:] for k in expr.split(' ') if k.startswith('@')]


def literals(expr):
    return [Fraction(k) for k in expr.split(' ') if re.fullmatch(r'\d+(\.\d+)?', k)]


def contiguous(small, big):
    s, b = small.split(' '), big.split(' ')
    return any(b[i:i + len(s)] == s for i in range(len(b) - len(s) + 1))


def F(x):
    return Fraction(str(x))


# ---------------------------------------------------------------- the contract's questions, derived from params
def expected(q):
    """(expected step values by id, allowed literal numbers, errors) derived from the parameters alone."""
    p, ty, errs = q['params'], q['type'], []
    exp, nums = {}, set()
    if ty == 'enough':
        rows, d, bud = p['rows'], p['d'], p['budget']
        if len(rows) not in (2, 3):
            errs.append('items: %d' % len(rows))
        total = Fraction(0)
        for i, r in enumerate(rows):
            if not 2 <= r['q'] <= 5 or r['p'] % 5 or not 100 <= r['p'] <= 2000:
                errs.append('item %d out of range: %s' % (i, r))
            exp['c%d' % (i + 1)] = Fraction(r['q'] * r['p'], 100)
            total += exp['c%d' % (i + 1)]
            nums |= {Fraction(r['q']), Fraction(r['p'], 100)}
        if d not in (10, 20, 25):
            errs.append('discount %s' % d)
        exp['total'] = total
        exp['discount'] = total * d / 100
        exp['price'] = total * (100 - d) / 100
        if (exp['price'] * 100).denominator != 1:
            errs.append('the price after the discount is not whole pence')
        lo, hi = exp['price'] * Fraction(85, 100), exp['price'] * Fraction(115, 100)
        b = Fraction(bud, 100)
        if not lo <= b <= hi:
            errs.append('budget %s not within 15%% of %s' % (b, exp['price']))
        if abs(b - exp['price']) < Fraction(20, 100):
            errs.append('budget %s is a tie with %s' % (b, exp['price']))
        nums |= {b, Fraction(d), Fraction(d, 100), Fraction(100 - d, 100)}
        text = ' '.join(q['stem'])
        for r in rows:
            if str(r['q']) not in text:
                errs.append('stem lacks a quantity')
        if '%d%%' % d not in text:
            errs.append('stem lacks the discount')
    elif ty == 'ratio':
        a, b, part, D = p['a'], p['b'], p['part'], p['D']
        if not (1 <= a < b and math.gcd(a, b) == 1 and a + b <= 12):
            errs.append('ratio %d:%d breaks a<b coprime a+b<=12' % (a, b))
        if D != part * (b - a) or part < 2:
            errs.append('the difference %s is not whole parts' % D)
        exp = {'diff': Fraction(b - a), 'part': Fraction(part), 'total': Fraction(part * (a + b))}
        nums = {Fraction(a), Fraction(b), Fraction(D)}
        text = ' '.join(q['stem'])
        if ('%d : %d' % (a, b)) not in text or str(D) not in text:
            errs.append('stem lacks the ratio or the difference')
    elif ty == 'interest':
        P, r, n, kind = p['P'], p['r'], p['n'], p['kind']
        if P % 100 or not 500 <= P <= 20000 or not 2 <= n <= 5:
            errs.append('P or n out of range')
        text = ' '.join(q['stem'])
        if kind == 'simple':
            if not 1 <= r <= 6:
                errs.append('simple rate %s' % r)
            if 'simple interest' not in text or 'compound' in text:
                errs.append('a simple question must say simple')
            exp = {'rate': Fraction(r, 100), 'year': Fraction(P * r, 100), 'total': Fraction(P * r * n, 100)}
            nums = {Fraction(P), Fraction(r), Fraction(n), Fraction(r, 100)}
        else:
            dep = kind == 'depreciation'
            if not (5 <= r <= 25 if dep else 1 <= r <= 6):
                errs.append('rate %s out of range for %s' % (r, kind))
            if not dep and 'compound interest' not in text:
                errs.append('a compound question must say compound')
            if dep and 'falls' not in text:
                errs.append('a depreciation question must say falls')
            m = Fraction(100 - r if dep else 100 + r, 100)
            exp = {'mult': m, 'year1': P * m, 'change1': Fraction(P * r, 100), 'final': P * m ** n}
            nums = {Fraction(P), Fraction(r), Fraction(n), Fraction(r, 100), m, Fraction(100 - r if dep else 100 + r)}
        if ('%s' % ('{:,}'.format(P))) not in text:
            errs.append('stem lacks the amount')
    else:
        W, H, cw, ch, pr = p['W'], p['H'], p['cw'], p['ch'], p['price']
        top, lr = W - cw, H - ch
        if not (3 <= top and 3 <= lr and cw >= 2 and ch >= 2 and W <= 15 and H <= 15 and cw != ch):
            errs.append('garden sides out of range: %s' % p)
        if not (200 <= pr <= 1200 and pr % 50 == 0):
            errs.append('price %s' % pr)
        areas = {W * H - cw * ch, top * H + cw * lr, W * lr + top * ch}
        if len(areas) != 1:
            errs.append('the three routes to the area disagree: %s' % sorted(areas))
        area = W * H - cw * ch
        exp = {'gapW': Fraction(cw), 'gapH': Fraction(ch), 'partA': Fraction(top * H), 'partB': Fraction(cw * lr),
               'partC': Fraction(W * lr), 'partD': Fraction(top * ch), 'big': Fraction(W * H), 'cut': Fraction(cw * ch),
               'area': Fraction(area), 'cost': Fraction(area * pr, 100)}
        nums = {Fraction(W), Fraction(H), Fraction(top), Fraction(lr), Fraction(pr, 100)}
        dg = q.get('diagram')
        if not dg or dg.get('kind') != 'lshape':
            errs.append('no diagram')
        else:
            lab = dg['labels']
            if (dg['W'], dg['H'], dg['cw'], dg['ch']) != (W, H, cw, ch):
                errs.append('diagram dimensions differ from the question')
            if lab != {'bottom': W, 'left': H, 'top': top, 'lowerRight': lr}:
                errs.append('diagram labels %s are not the sides %s' % (lab, (W, H, top, lr)))
    return exp, nums, errs


def check_question(q):
    errs = []
    exp, nums, e = expected(q)
    errs += e
    if q['marks'] != 4 or len(q['slots']) != 3:
        errs.append('not 4 marks = 3 method + 1 answer')
    slot_ids = {s['id'] for s in q['slots']}
    ids = [s['id'] for s in q['steps']]
    if set(ids) != set(exp):
        errs.append('steps %s differ from the expected %s' % (sorted(ids), sorted(exp)))
    vals, ancestors, seen = {}, {}, []
    for st in q['steps']:
        sid = st['id']
        if st['slot'] is not None and st['slot'] not in slot_ids:
            errs.append('%s: unknown slot %s' % (sid, st['slot']))
        anc = set()
        form_vals = []
        for f in st['forms']:
            try:
                v = evaluate(f['expr'], vals)
            except Exception as ex:  # noqa: BLE001
                errs.append('%s: cannot evaluate %r (%s)' % (sid, f['expr'], ex))
                continue
            form_vals.append(v)
            deps = set(f['deps'])
            for r in refs(f['expr']):
                if r not in deps:
                    errs.append('%s: @%s is not among its deps' % (sid, r))
            for d in deps:
                if d not in seen:
                    errs.append('%s: dep %s is not an earlier step' % (sid, d))
                anc |= {d} | ancestors.get(d, set())
            allowed = set(nums) | {vals[a] for a in anc if a in vals}
            for lit in literals(f['expr']):
                if lit not in allowed:
                    errs.append('%s: %s in %r is not a number of the question or a found result (a step offered before its inputs)'
                                % (sid, lit, f['expr']))
            for im in f['implies']:
                other = next((s for s in q['steps'] if s['id'] == im), None)
                if not other or im not in seen or not any(contiguous(g['expr'], f['expr']) for g in other['forms']):
                    errs.append('%s: implies %s, which its calculation does not show' % (sid, im))
        if form_vals:
            if any(v != form_vals[0] for v in form_vals):
                errs.append('%s: its forms disagree: %s' % (sid, [str(v) for v in form_vals]))
            vals[sid] = form_vals[0]
            if sid in exp and form_vals[0] != exp[sid]:
                errs.append('%s: value %s, recomputed from the question %s' % (sid, form_vals[0], exp[sid]))
            if abs(float(form_vals[0]) - st['value']) > 1e-6 * max(1, abs(st['value'])):
                errs.append('%s: the module says %s, this says %s' % (sid, st['value'], float(form_vals[0])))
        ancestors[sid] = anc
        seen.append(sid)
    tex_seen = set()
    for i, d in enumerate(q['distractors']):
        try:
            v = evaluate(d['expr'], vals)
        except Exception as ex:  # noqa: BLE001
            errs.append('distractor %d: cannot evaluate %r (%s)' % (i, d['expr'], ex))
            continue
        for sid, sv in vals.items():
            if v == sv:
                errs.append('distractor %r has the value of step %s (%s): a true statement offered as wrong' % (d['expr'], sid, sv))
        if d['tex'] in tex_seen:
            errs.append('two distractors are the same calculation: %s' % d['tex'])
        tex_seen.add(d['tex'])
        for r in refs(d['expr']):
            if r not in d['deps']:
                errs.append('distractor %r: @%s is not among its deps' % (d['expr'], r))
        if d['for'] not in vals:
            errs.append('distractor %r is for no step' % d['expr'])
        if not d['why'] or len(d['why']) > 200:
            errs.append('distractor %r: its slip line is missing or long' % d['expr'])
    for st in q['steps']:                      # a step's calculation is never also a distractor
        for f in st['forms']:
            if f['tex'] in tex_seen:
                errs.append('%s: a form is also a distractor' % st['id'])
    return errs


