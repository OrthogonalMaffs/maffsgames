# ---------------------------------------------------------------- our own expression parser (Fractions)
def evaluate(expr, vals):
    t = expr.split(' ')
    pos = [0]

    def peek():
        return t[pos[0]] if pos[0] < len(t) else None

    def take():
        pos[0] += 1
        return t[pos[0] - 1]

    def atom():
        k = take()
        if k == '(':
            v = total()
            assert take() == ')'
            return v
        if k.startswith('@'):
            return vals[k[1:]]
        if k == 'sqrt':
            r = isqrt_fraction(atom())
            assert r is not None, 'the square root is not exact'
            return r
        v = Fraction(k)
        if peek() == '%':
            take()
            v = v / 100
        return v

    def power():
        b = atom()
        if peek() == '^':
            take()
            e = power()
            assert e.denominator == 1
            return b ** int(e)
        return b

    def prod():
        v = power()
        while peek() in ('*', '/'):
            op = take()
            r = power()
            v = v * r if op == '*' else v / r
        return v

    def total():
        v = prod()
        while peek() in ('+', '-'):
            op = take()
            r = prod()
            v = v + r if op == '+' else v - r
        return v

    out = total()
    assert pos[0] == len(t), 'trailing tokens'
    return out


def refs(expr):
    return [k[1:] for k in expr.split(' ') if k.startswith('@')]


def literals(expr):
    return [Fraction(k) for k in expr.split(' ') if re.fullmatch(r'\d+(\.\d+)?', k)]


def contiguous(small, big):
    s, b = small.split(' '), big.split(' ')
    return any(b[i:i + len(s)] == s for i in range(len(b) - len(s) + 1))


def F(x):
    return Fraction(str(x))


