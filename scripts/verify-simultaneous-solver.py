def play(fails, bank, alevel, katex_dir=None, shots=None):
    import asyncio
    sys.path.insert(0, os.path.join(ROOT, "scripts"))
    import bank_common as bc

    def right_answers(it, stage, letter=None):
        """The answer for each step, in order: (kind, value)."""
        L = letter or it.get("elim")
        i = 0 if L == "x" else 1
        m = lcm_pair(it["e"][0][i], it["e"][1][i])
        s = [[m[0] * v for v in it["e"][0]], [m[1] * v for v in it["e"][1]]]
        sub = (s[0][i] > 0) == (s[1][i] > 0)
        comb = [s[0][k] - s[1][k] if sub else s[0][k] + s[1][k] for k in range(3)]
        o = "y" if L == "x" else "x"
        steps = []
        if stage == "stage4":
            steps.append(("choose", L))
        steps.append(("type", [str(m[0]), str(m[1])]))
        if stage != "stage1":
            steps.append(("choose", "sub" if sub else "add"))
            steps.append(("type", [str(comb[1 - i]), str(comb[2])]))
        if stage in ("stage3", "stage4"):
            steps.append(("type", [str(it[o])]))
            steps.append(("type", [str(it[L])]))
        return steps

    async def run(base):
        from playwright.async_api import async_playwright
        async with async_playwright() as p:
            browser = await p.chromium.launch()

            async def route(r):
                u = r.request.url
                if katex_dir and u.startswith("https://cdn.jsdelivr.net/npm/katex"):
                    f = os.path.join(katex_dir, u.split("/dist/", 1)[1].split("?")[0])
                    await (r.fulfill(path=f) if os.path.exists(f) else r.abort())
                elif u.startswith(base) or u.startswith("https://cdn.jsdelivr.net/npm/katex"):
                    await r.continue_()
                else:
                    await r.abort()

            async def fresh(w, h, touch=False, aa=False):
                ctx = await browser.new_context(viewport={"width": w, "height": h}, has_touch=touch, is_mobile=touch)
                await bc.no_next_floor(ctx)
                if aa:
                    await ctx.add_init_script("try { localStorage.setItem('mfg_accessible', 'true'); } catch (e) {}")
                await ctx.route("**/*", route)
                page = await ctx.new_page()
                errors = []
                page.on("pageerror", lambda e: errors.append(str(e)))
                await page.goto(base + "/games/%s/" % SLUG, wait_until="load")
                await page.wait_for_function("!!window.SS && !!window.SS.ui")
                await page.evaluate("""() => { window.__events = []; window.__submits = [];
                  window.mfg = function (n, p) { window.__events.push([n, p]); };
                  if (window.MaffsLeaderboard) MaffsLeaderboard.submitScore = function (s, l, sc, n) {
                    window.__submits.push([s, l, sc, n]); return Promise.resolve({}); }; }""")
                return ctx, page, errors

            async def do(page, kind, val):
                if kind == "choose":
                    if not await page.evaluate("v => SS.ui.choose(v)", val):
                        fails.append("page: no %r choice at step %r" % (val, await page.evaluate("SS.ui.state()")))
                else:
                    await page.evaluate("v => SS.ui.type(v)", val)
                    await page.click("#checkBtn")

            async def next_btn(page):
                if await page.locator(".maffs-next").count():
                    await page.click(".maffs-next")
                    return True
                return False

            ctx, page, errors = await fresh(390, 844)
            # 1. Stage 1 marking: every pair 1..12, negatives, x0 and 1.5.
            res = await page.evaluate("""(items) => items.map(it => { const out = [];
              for (let a = 1; a <= 12; a++) for (let b = 1; b <= 12; b++) out.push(SS.markMult(it.e, it.elim, String(a), String(b)).result);
              const n = it.m;
              return { grid: out, neg: SS.markMult(it.e, it.elim, String(-n[0]), String(n[1])).result,
                zero: SS.markMult(it.e, it.elim, '0', String(n[1])).result, half: SS.markMult(it.e, it.elim, '1.5', String(n[1])).result,
                neatest: SS.markMult(it.e, it.elim, String(n[0]), String(n[1])).neatest }; })""", bank["stage1"])
            pairs = 0
            for it, r in zip(bank["stage1"], res):
                i = 0 if it["elim"] == "x" else 1
                k = 0
                for a in range(1, 13):
                    for b in range(1, 13):
                        want = "correct" if abs(a * it["e"][0][i]) == abs(b * it["e"][1][i]) else "wrong"
                        if r["grid"][k] != want:
                            fails.append("page, %s: x%d and x%d marked %s, expected %s" % (it["id"], a, b, r["grid"][k], want))
                        k += 1
                        pairs += 1
                if r["neg"] != "correct" or r["zero"] != "blocked" or r["half"] != "whole" or not r["neatest"]:
                    fails.append("page, %s: negative %s, x0 %s, x1.5 %s, neatest flagged %s" % (it["id"], r["neg"], r["zero"], r["half"], r["neatest"]))
            # 2. The page's algebra against this script's on every problem.
            for st in STAGES[1:]:
                for it in bank[st]:
                    L = it.get("elim") or (it["neat"] if it["neat"] in ("x", "y") else "x")
                    steps = right_answers(it, st, L)
                    got = await page.evaluate("""([it, L]) => { const i = L === 'x' ? 0 : 1, m = SS.neat(it.e[0][i], it.e[1][i]),
                      s = SS.scale(it.e, m), op = SS.opFor(s, L), c = SS.combine(s, L, op); return [op, String(c.K), String(c.C)]; }""", [it, L])
                    want = [steps[-4 if st != "stage2" else -2][1], steps[-3 if st != "stage2" else -1][1][0], steps[-3 if st != "stage2" else -1][1][1]]
                    if got != want:
                        fails.append("page, %s: op and combined %r, expected %r" % (it["id"], got, want))
            # 3a. x4/x6 where x2/x3 is neatest (or the first both-scaled pair, doubled).
            it = next((x for x in bank["stage1"] if x["m"] == [2, 3]), None) or next(x for x in bank["stage1"] if min(x["m"]) > 1)
            n = it["m"]
            await page.evaluate("id => SS.ui.startWith('stage1', [id])", it["id"])
            await do(page, "type", [str(2 * n[0]), str(2 * n[1])])
            got = await page.evaluate("""() => { const w = document.querySelector('#working .wl'), ne = w && w.querySelector('.neatest');
              return [SS.ui.score(), w ? w.className : '', ne ? ne.innerText.replace(/\\s+/g, ' ') : null]; }""")
            if got[0] != 1 or "right" not in got[1] or not got[2] or ("×%d" % n[0]) not in got[2] or ("×%d" % n[1]) not in got[2]:
                fails.append("page, %s: x%d/x%d (neatest x%d/x%d) scored %r and showed %r" % (it["id"], 2 * n[0], 2 * n[1], n[0], n[1], got[0], got[2]))
            # 3b. Add where subtract was needed: the letter doubles.
            it = next(x for x in bank["stage2"] if right_answers(x, "stage2")[1] == ("choose", "sub"))
            await page.evaluate("id => SS.ui.startWith('stage2', [id])", it["id"])
            steps = right_answers(it, "stage2")
            await do(page, *steps[0])
            await do(page, "choose", "add")
            i = 0 if it["elim"] == "x" else 1
            dbl = 2 * it["m"][0] * it["e"][0][i]
            got = await page.evaluate("""() => { const f = document.getElementById('feedback'), d = f.querySelector('.doubled');
              return [f.innerText.replace(/\\s+/g, ' '), d ? d.innerText.replace(/\\s+/g, '') : null]; }""")
            if "doubles instead of vanishing" not in got[0] or not got[1] or str(abs(dbl)) not in got[1]:
                fails.append("page, %s: add instead of subtract showed %r (the doubled term %d%s not shown)" % (it["id"], got, dbl, it["elim"]))
            # 3c. A wrong combined equation: the working term by term, subtracting a negative in brackets.
            it = next(x for x in bank["stage2"] if "subtracting a negative" in negative_work(x["e"], x["elim"]))
            await page.evaluate("id => SS.ui.startWith('stage2', [id])", it["id"])
            steps = right_answers(it, "stage2")
            await do(page, *steps[0])
            await do(page, *steps[1])
            await do(page, "type", [str(int(steps[2][1][0]) + 1), steps[2][1][1]])
            got = await page.evaluate("""() => { const w = document.querySelector('#feedback .fb-work');
              return w ? [w.children.length, w.innerText.replace(/\\s+/g, '')] : null; }""")
            if not got or got[0] != 6 or not re.search(r"−\(−", got[1]):
                fails.append("page, %s: a wrong combined equation showed %r, not three term-by-term lines with − (−…)" % (it["id"], got))
            await next_btn(page)
            # 4. A full game of every stage, every step right.
            for st in STAGES:
                await page.evaluate("SS.ui.restart()")
                await page.evaluate("""s => { document.querySelector('.tab[data-level="gcse"]').click();
                  document.querySelector('.stage-btn[data-stage="' + s + '"]').click(); }""", st)
                await page.evaluate("window.__events = []; window.__submits = [];")
                await page.click("#startBtn")
                nexts = 0
                for k in range(ROUNDS[st]):
                    it = await page.evaluate("SS.ui.item()")
                    letter = (it["neat"] if it["neat"] in ("x", "y") else "y") if st == "stage4" else None
                    for kind, val in right_answers(it, st, letter):
                        await do(page, kind, val)
                    nexts += await next_btn(page)
                stt = await page.evaluate("[SS.ui.state(), SS.ui.score(), SS.ui.maxMarks(), !!document.querySelector('#timer, .timer, .hud-timer')]")
                want = ROUNDS[st] * STEPS[st]
                if stt[0] != "done" or stt[1] != want or stt[2] != want or stt[3] or nexts != ROUNDS[st]:
                    fails.append("page, %s full game: state %r, score %r of %r (want %d), timer %s, Next %d times" % (st, stt[0], stt[1], stt[2], want, stt[3], nexts))
                subs = await page.evaluate("window.__submits")
                if subs != [[SLUG, BOARDS[st], want, ROUNDS[st]]]:
                    fails.append("page, %s: leaderboard submissions %r, expected one to %s" % (st, subs, BOARDS[st]))
                ev = await page.evaluate("window.__events")
                bad = [n for n, pr in ev if pr.get("mode") != st or (n != "mode_selected" and pr.get("level") != "gcse")]
                if bad or not any(n == "game_completed" for n, _ in ev):
                    fails.append("page, %s: events without mode %s or level gcse: %r" % (st, st, bad))
            # 5. The A-Level level, every answer right, then one wrong answer waits for Next.
            await page.evaluate("SS.ui.restart()")
            await page.evaluate("document.querySelector('.tab[data-level=\"alevel\"]').click(); window.__events = []; window.__submits = [];")
            await page.click("#startBtn")
            for k in range(20):
                c = (await page.evaluate("SS.ui.mcItem()"))["correct"]
                await page.locator("#mcOptions .opt-btn").filter(has=page.locator("xpath=.")).nth(0).wait_for()
                await page.evaluate("c => [...document.querySelectorAll('#mcOptions .opt-btn')].find(b => b.dataset.val === c).click()", c)
                await page.wait_for_function("SS.ui.state() === 'done' || (SS.ui.mcItem() && document.querySelectorAll('#mcOptions .opt-btn:disabled').length === 0)")
            stt = await page.evaluate("[SS.ui.state(), SS.ui.score()]")
            subs = await page.evaluate("window.__submits")
            if stt != ["done", 2000] or subs != [[SLUG, "alevel", 2000, 20]]:
                fails.append("page, A-Level: state and score %r, submissions %r (want 2000 on 'alevel')" % (stt, subs))
            ev = await page.evaluate("window.__events")
            if any(pr.get("mode") != "choice" or pr.get("level") != "alevel" for n, pr in ev):
                fails.append("page, A-Level: an event without mode 'choice' or level 'alevel': %r" % ev[:3])
            await page.evaluate("SS.ui.startWith('alevel', ['a01'])")
            await page.evaluate("[...document.querySelectorAll('#mcOptions .opt-btn')].find(b => b.dataset.val !== SS.ui.mcItem().correct).click()")
            if not await page.locator("#mcFeedback .maffs-next").count():
                fails.append("page, A-Level: a wrong answer shows no Next control")
            for e in errors:
                fails.append("page error: %s" % e)
            await ctx.close()

            # 6. A full Stage 4 problem on the keypad, on phones: every step and its keypad in the window together.
            it4 = next(x for x in bank["stage4"] if x["neat"] in ("x", "y") and negative_work(x["e"], x["neat"]))
            for (w, h) in PHONES:
                for aa in (False, True):
                    tag = "%dx%d%s" % (w, h, " Aa" if aa else "")
                    ctx, page, errors = await fresh(w, h, touch=True, aa=aa)
                    await page.evaluate("id => SS.ui.startWith('stage4', [id])", it4["id"])
                    for sn, (kind, val) in enumerate(right_answers(it4, "stage4", it4["neat"])):
                        m = await page.evaluate(FIT_JS)
                        if m["top"] < 0 or m["bottom"] > m["fold"]:
                            fails.append("%s %s step %d: the step and its keypad span y=%.0f..%.0f, the window ends at %.0f"
                                         % (tag, it4["id"], sn + 1, m["top"], m["bottom"], m["fold"]))
                        if m["sw"] > m["cw"]:
                            fails.append("%s %s step %d: the page is %dpx wide" % (tag, it4["id"], sn + 1, m["sw"]))
                        if shots and not aa:
                            await page.screenshot(path=os.path.join(shots, "ss-%dx%d-step%d.png" % (w, h, sn + 1)))
                        if kind == "choose":
                            await page.locator('.choice[data-val="%s"]' % val).tap()
                            continue
                        boxes = page.locator("#stepBody input")
                        if await boxes.count() != len(val):
                            fails.append("%s step %d: %d boxes, expected %d" % (tag, sn + 1, await boxes.count(), len(val)))
                            break
                        for bi, v in enumerate(val):
                            await boxes.nth(bi).tap()
                            for ch in v:
                                await page.locator('.maffs-keypad-key[data-act="%s"]%s' % (("minus", "") if ch == "-" else ("in", '[data-val="%s"]' % ch))).tap()
                        got = await page.evaluate("[...document.querySelectorAll('#stepBody input')].map(i => i.value)")
                        if got != val:
                            fails.append("%s step %d: the keypad typed %r, expected %r" % (tag, sn + 1, got, val))
                        if (await page.evaluate(FIT_JS))["focused"]:
                            fails.append("%s step %d: a box took focus (the system keyboard would open)" % (tag, sn + 1))
                        await page.locator("#checkBtn").tap()
                    st4 = await page.evaluate("[SS.ui.state(), SS.ui.score()]")
                    nb = await page.evaluate("(() => { const b = document.querySelector('#feedback .maffs-next'); if (!b) return null; "
                                             "const r = b.getBoundingClientRect(), f = document.getElementById('feedback').getBoundingClientRect(); "
                                             "return [r.bottom, innerHeight - 40, f.top]; })()")
                    if st4 != ["feedback", 5]:
                        fails.append("%s: the Stage 4 problem played on the keypad ended %r, expected ['feedback', 5]" % (tag, st4))
                    if nb is None or nb[0] > nb[1] or nb[2] < 0:
                        fails.append("%s: the answer and Next are not all in the window (Next bottom, fold, feedback top: %r)" % (tag, nb))
                    if shots and not aa:
                        await page.screenshot(path=os.path.join(shots, "ss-%dx%d-end.png" % (w, h)))
                    for e in errors:
                        fails.append("%s page error: %s" % (tag, e))
                    await ctx.close()
            await browser.close()
            return pairs

