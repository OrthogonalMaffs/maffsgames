        sy = [sp.Symbol(l) for l in L]
        sol = sp.solve([sp.Rational(v[0]) * sy[0] + sp.Rational(v[1]) * sy[1] + sp.Rational(v[2]) for v in vecs], sy, dict=True)
        want = {sp.Symbol(k): sp.Rational(x) for k, x in S5_SOLUTIONS.get(wid, {}).items()}
