# ---------------------------------------------------------------- Foundation rules
def lcm_pair(p, q):
    l = abs(p) * abs(q) // math.gcd(abs(p), abs(q))
    return [l // abs(p), l // abs(q)]


def exact_solution(e):
    (a1, b1, c1), (a2, b2, c2) = e
    det = a1 * b2 - a2 * b1
    if det == 0:
        return None
    return Fraction(c1 * b2 - c2 * b1, det), Fraction(a1 * c2 - a2 * c1, det)


def neater_letter(e):
    def cost(i):
        m = lcm_pair(e[0][i], e[1][i])
        return (abs(e[0][i]) * m[0], sum(v != 1 for v in m))
    cx, cy = cost(0), cost(1)
    return "x" if cx < cy else "y" if cy < cx else "either"


def negative_work(e, letter):
    """The kinds of negative work in eliminating this letter, neatest scaling, (1) first."""
    i = 0 if letter == "x" else 1
    m = lcm_pair(e[0][i], e[1][i])
    s = [[m[0] * v for v in e[0]], [m[1] * v for v in e[1]]]
    sub = (s[0][i] > 0) == (s[1][i] > 0)
    comb = [s[0][k] - s[1][k] if sub else s[0][k] + s[1][k] for k in range(3)]
    kinds = set()
    if sub and any(v < 0 for v in s[1]):
        kinds.add("subtracting a negative")
    if not sub and any(u < 0 and v < 0 for u, v in zip(s[0], s[1])):
        kinds.add("adding two negatives")
    if comb[1 - i] < 0 or comb[2] < 0:
        kinds.add("a negative result")
    return kinds


def check_foundation(bank, report=None):
    fails = []
    for st in STAGES:
        items = bank.get(st, [])
        if len(items) < MIN_PER_STAGE:
            fails.append("%s: %d problems, at least %d needed" % (st, len(items), MIN_PER_STAGE))
        seen, ids = {}, set()
        for it in items:
            iid, e = it.get("id"), it.get("e")
            if iid in ids:
                fails.append("%s: id %s used twice" % (st, iid))
            ids.add(iid)
            if not (isinstance(e, list) and len(e) == 2 and all(isinstance(r, list) and len(r) == 3 and all(isinstance(v, int) for v in r) for r in e)):
                fails.append("%s: malformed equations %r" % (iid, e))
                continue
            if any(not 1 <= abs(v) <= 12 for r in e for v in r[:2]):
                fails.append("%s: a coefficient is not 1 to 12 in size: %r" % (iid, e))
            sol = exact_solution(e)
            if sol is None:
                fails.append("%s: no single solution (no solution, or infinitely many): %r" % (iid, e))
                continue
            x, y = sol
            if x.denominator != 1 or y.denominator != 1:
                fails.append("%s: the solution is not whole: x = %s, y = %s" % (iid, x, y))
            elif not (-10 <= x <= 10 and -10 <= y <= 10):
                fails.append("%s: the solution x = %s, y = %s is outside -10..10" % (iid, x, y))
            elif (int(x), int(y)) != (it.get("x"), it.get("y")):
                fails.append("%s: stored x = %r, y = %r, but the solution is x = %s, y = %s" % (iid, it.get("x"), it.get("y"), x, y))
            k = tuple(sorted(tuple(r) for r in e))
            if k in seen:
                fails.append("%s: the same problem as %s" % (iid, seen[k]))
            seen[k] = iid
            letters = ["x", "y"] if st == "stage4" else [it.get("elim")]
            for L in letters:
                if L not in ("x", "y"):
                    fails.append("%s: elim is %r, not x or y" % (iid, L))
                    continue
                i = 0 if L == "x" else 1
                want = lcm_pair(e[0][i], e[1][i])
                got = it.get("m" + L) if st == "stage4" else it.get("m")
                if got != want:
                    fails.append("%s: the neatest multipliers for %s are %r, the bank says %r" % (iid, L, want, got))
                if max(want) > 5:
                    fails.append("%s: the neatest multipliers for %s are %r, more than 5" % (iid, L, want))
            if st == "stage4" and it.get("neat") != neater_letter(e):
                fails.append("%s: the neater letter is %s, the bank says %r" % (iid, neater_letter(e), it.get("neat")))
        if st == "stage1":
            ones = sum(1 for it in items if 1 in (it.get("m") or []))
            if ones < 5:
                fails.append("stage1: only %d problems with a x1 multiplier (some are needed)" % ones)
            if report is not None:
                report.append("stage1: %d problems, %d with a x1 multiplier" % (len(items), ones))
        else:
            neg, kinds = 0, {"subtracting a negative": 0, "adding two negatives": 0, "a negative result": 0}
            for it in items:
                if any(v < 0 for r in it["e"] for v in r):
                    neg += 1
                L = it.get("elim") or (it.get("neat") if it.get("neat") in ("x", "y") else "x")
                for kd in negative_work(it["e"], L):
                    kinds[kd] += 1
            n = max(len(items), 1)
            if 3 * neg < 2 * n:
                fails.append("%s: only %d of %d problems have a negative coefficient or constant (two-thirds needed)" % (st, neg, n))
            for kd, c in kinds.items():
                if 8 * c < n:
                    fails.append("%s: only %d of %d problems involve %s (an eighth needed)" % (st, c, n, kd))
            if report is not None:
                report.append("%s: %d problems; a negative coefficient or constant in %d (%.0f%%); %s"
                              % (st, n, neg, 100.0 * neg / n, ", ".join("%s %d" % kv for kv in kinds.items())))
    return fails


# ---------------------------------------------------------------- A-Level keys
X, Y = sp.symbols("x y")


def tex_expr(t):
    s = t.replace("\\dfrac", "\\tfrac")
    s = re.sub(r"\\sqrt\{([^{}]*)\}", r"sqrt(\1)", s)
    s = re.sub(r"\\tfrac\{([^{}]*)\}\{([^{}]*)\}", r"((\1)/(\2))", s)
    s = s.replace("^", "**")
    s = re.sub(r"(\d)\s*([xy(]|sqrt)", r"\1*\2", s)
    if "\\" in s:
        raise ValueError("unparsed TeX in %r" % t)
    return sp.nsimplify(sp.sympify(s, locals={"x": X, "y": Y}))


def alevel_key(item):
    eqs = []
    for t in item["sys"]:
        l, r = t.split("=")
        eqs.append(sp.Eq(tex_expr(l), tex_expr(r)))
    sols = [s for s in sp.solve(eqs, [X, Y], dict=True) if all(v.is_real for v in s.values())]
    sols = list({(sp.simplify(s[X]), sp.simplify(s[Y])) for s in sols})
    ask = item["ask"]
    xs = sorted({s[0] for s in sols}, key=lambda v: float(v))
    if ask == "How many solutions?":
        return sp.Integer(len(sols))
    if ask in ("Find x", "Find y"):
        if len(sols) != 1:
            raise ValueError("%d solutions for a 'Find' question" % len(sols))
        return sols[0][0] if ask == "Find x" else sols[0][1]
    if ask == "Find the values of x (sum)":
        return sp.simplify(sum(xs))
    m = re.match(r"Find the (positive|negative|non-zero|larger|smaller) ([xy]) value$", ask)
    if not m:
        raise ValueError("an ask this script cannot read: %r" % ask)
    vals = sorted({s[0 if m.group(2) == "x" else 1] for s in sols}, key=lambda v: float(v))
    pick = {"positive": [v for v in vals if v > 0], "negative": [v for v in vals if v < 0],
            "non-zero": [v for v in vals if v != 0], "larger": vals[-1:] if len(vals) == 2 else [],
            "smaller": vals[:1] if len(vals) == 2 else []}[m.group(1)]
    if len(pick) != 1:
        raise ValueError("'%s' picks %d values from %r" % (ask, len(pick), vals))
    return pick[0]


def check_alevel(items):
    fails, ids = [], set()
    if len(items) < MIN_ALEVEL:
        fails.append("alevel: %d questions, at least %d needed" % (len(items), MIN_ALEVEL))
    for it in items:
        iid = it.get("id")
        if iid in ids:
            fails.append("alevel: id %s used twice" % iid)
        ids.add(iid)
        try:
            key = alevel_key(it)
            opts = [it["correct"]] + list(it["distractors"])
            vals = [tex_expr(o) for o in opts]
        except Exception as exc:
            fails.append("%s: %s" % (iid, exc))
            continue
        if len(opts) != 4:
            fails.append("%s: %d options, 4 needed" % (iid, len(opts)))
        if sp.simplify(vals[0] - key) != 0:
            fails.append("%s: the key is %s, but %r (%s) is stored" % (iid, key, it["correct"], vals[0]))
        for a in range(len(vals)):
            for b in range(a + 1, len(vals)):
                if sp.simplify(vals[a] - vals[b]) == 0:
                    fails.append("%s: options %r and %r are equal in value (SR-4)" % (iid, opts[a], opts[b]))
    return fails


# ---------------------------------------------------------------- self-test
def selftest(bank, alevel):
    out = []

    def plant(name, fn, needle, which="f"):
        b, a = copy.deepcopy(bank), copy.deepcopy(alevel)
        fn(b, a)
        f = check_foundation(b) if which == "f" else check_alevel(a)
        hit = [x for x in f if needle in x]
        out.append(None if hit else "self-test: the planted %s was not caught" % name)

    def non_integer(b, a):
        it = b["stage2"][0]
        for d in range(1, 13):          # bounded: the first change of c1 that makes the solution not whole
            e = copy.deepcopy(it["e"])
            e[0][2] += d
            s = exact_solution(e)
            if s and (s[0].denominator != 1 or s[1].denominator != 1):
                it["e"] = e
                return

    def wrong_pair(b, a):
        b["stage1"][0]["m"] = [v * 2 for v in b["stage1"][0]["m"]]

    def positives_only(b, a):
        for it in b["stage3"]:
            x, y = abs(it["x"]), abs(it["y"])
            e = [[abs(r[0]), abs(r[1])] for r in it["e"]]
            it["e"] = [[r[0], r[1], r[0] * x + r[1] * y] for r in e]
            it["x"], it["y"] = x, y

    def wrong_key(b, a):
        a[0]["correct"] = "7"

    plant("non-integer solution", non_integer, "not whole")
    plant("wrong neatest pair", wrong_pair, "the bank says")
    plant("positives-only stage", positives_only, "have a negative coefficient or constant")
    plant("wrong A-Level key", wrong_key, "the key is", which="a")
    return [x for x in out if x]


