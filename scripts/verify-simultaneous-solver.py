def block(src, start, end):
    m = re.search(re.escape(start) + r"\s*var\s+\w+\s*=\s*(.*?);?\s*" + re.escape(end), src, re.S)
    if not m:
        raise SystemExit("verify-simultaneous-solver: no %s ... %s block in the page" % (start, end))
    return json.loads(m.group(1))


