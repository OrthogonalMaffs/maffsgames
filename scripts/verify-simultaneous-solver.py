        if det == 0 or len(sol) != 1 or sol[0] != want:
            fails.append("stage5 %s: the keys %s do not have exactly the one solution %s (got %s)" % (wid, w["keys"], want, sol))
        elif not all(x > 0 for x in want.values()):
            fails.append("stage5 %s: the solution %s is not positive" % (wid, want))
        if not all(re.search(r"\b%s\b" % l, w["let"]) for l in L):
            fails.append("stage5 %s: the Let line does not name both letters %s" % (wid, L))
        for j, s in enumerate(w["src"]):
            if s not in w["text"]:
                fails.append("stage5 %s: key %d's source words %r are not in the problem" % (wid, j + 1, s))
        need = {Fraction(t["v"].replace(",", "")) for k in w["keys"] for t in s5_tokens(k) if t["k"] == "n"}
