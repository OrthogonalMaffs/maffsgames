def s5_tokens(s):
    out = []
    for m in re.finditer(r"(\d[\d,]*(?:\.\d+)?)|([a-z])|([+=])|([-−])", s):
        out.append({"k": "n", "v": m.group(1)} if m.group(1) else {"k": "l", "v": m.group(2)} if m.group(2)
                   else {"k": m.group(3)} if m.group(3) else {"k": "-"})
    return out


def s5_letters(item):
    out = []
    for c in re.findall(r"[a-z]", " ".join(item["keys"])):
        if c not in out:
            out.append(c)
    return out


def s5_vec(tokens, letters):
    """This script's own reading of a line: [A, B, C] for A l1 + B l2 + C = 0, exact; None if not an equation."""
    def side(t):
        acc, i, sign = [Fraction(0)] * 3, 0, 1
        if not t:
            return None
        if t[0]["k"] in "+-":
            sign, i = (-1 if t[0]["k"] == "-" else 1), 1
        while True:
            c, at, has = Fraction(1), 2, False
            if i < len(t) and t[i]["k"] == "n":
                c, has, i = Fraction(t[i]["v"].replace(",", "")), True, i + 1
            if i < len(t) and t[i]["k"] == "l":
                if t[i]["v"] not in letters:
                    return None
                at, has, i = letters.index(t[i]["v"]), True, i + 1
            if not has:
                return None
            acc[at] += sign * c
            if i >= len(t):
                return acc
            if t[i]["k"] not in "+-":
                return None
            sign, i = (-1 if t[i]["k"] == "-" else 1), i + 1
            if i >= len(t):
                return None
    eqs = [i for i, x in enumerate(tokens) if x["k"] == "="]
    if len(eqs) != 1:
        return None
    L, R = side(tokens[:eqs[0]]), side(tokens[eqs[0] + 1:])
    if L is None or R is None:
        return None
    v = [L[j] - R[j] for j in range(3)]
    return v if (v[0] or v[1]) else None


def s5_multiple(v, k):
    return v is not None and (v[0] or v[1]) and all(v[a] * k[b] == v[b] * k[a] for a in range(3) for b in range(a + 1, 3))


def s5_emit(terms):
    """Tokens for a side: terms are (Fraction coefficient, letter or None); zero terms dropped; '0' if empty."""
    out = []
    for c, l in terms:
        if c == 0:
            continue
        if out:
            out.append({"k": "+" if c > 0 else "-"})
        elif c < 0:
            out.append({"k": "-"})
        a = abs(c)
        if l is None or a != 1:
            out.append({"k": "n", "v": s5_num(a)})
        if l is not None:
            out.append({"k": "l", "v": l})
    return out or [{"k": "n", "v": "0"}]


def s5_num(f):
    """A terminating fraction as the decimal a tile shows: 3/10 -> "0.3", 1070 -> "1070"."""
    s = format(Decimal(f.numerator) / Decimal(f.denominator), "f")
    return s.rstrip("0").rstrip(".") if "." in s else s


def s5_forms(item):
    """For each key: the forms the marker must accept and reject (tokens), each with a name."""
    L = s5_letters(item)
    out = []
    for j, key in enumerate(item["keys"]):
        kt = s5_tokens(key)
        e = kt.index({"k": "="})
        A, B, C = s5_vec(kt, L)          # A l1 + B l2 + C = 0
        ints = all(x.denominator == 1 for x in (A, B, C))
        f = Fraction(1, 10) if ints else Fraction(100)
        money = "pounds" in item["let"]
        accept = [("the key", kt), ("sides swapped", kt[e + 1:] + [{"k": "="}] + kt[:e]),
                  ("rearranged", s5_emit([(A, L[0])]) + [{"k": "="}] + s5_emit([(-C, None), (-B, L[1])])),
                  ("scaled by %s" % f, s5_emit([(A * f, L[0]), (B * f, L[1])]) + [{"k": "="}] + s5_emit([(-C * f, None)]))]
        part = Fraction(100 if money else 10)
        partly = (s5_emit([(A, L[0]), (B, L[1])]) + [{"k": "="}] + s5_emit([(-C * part, None)])) if C else \
            (s5_emit([(A * part, L[0]), (B, L[1])]) + [{"k": "="}] + s5_emit([(Fraction(0), None)]))
        reject = [("partly scaled (x%s on %s only)" % (part, "the total" if C else "one term"), partly),
                  ("an arithmetic slip (the total off by 1)", s5_emit([(A, L[0]), (B, L[1])]) + [{"k": "="}] + s5_emit([(-C + 1, None)]))]
        out.append((j, accept, reject))
    return out


