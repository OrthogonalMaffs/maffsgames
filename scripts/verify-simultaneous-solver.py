def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--static", action="store_true", help="the banks only, no browser")
    ap.add_argument("--katex-dir", help="serve KaTeX from this copy of its dist/ folder (a sandbox where the CDN is blocked)")
    ap.add_argument("--shots", help="save the phone screenshots of the Stage 4 problem here")
    args = ap.parse_args()
    bank, alevel = read_banks()
    fails = selftest(bank, alevel)
    report = []
    fails += check_foundation(bank, report)
    fails += check_alevel(alevel)
    gen = load_gen()
    if gen.render(gen.build()) != open(PAGE, encoding="utf-8").read().split("/* GENERATED BANK START */\n", 1)[1].split("\n/* GENERATED BANK END */", 1)[0]:
        fails.append("the page's bank is not what scripts/gen-simultaneous.py generates (run it with --write)")
    pairs = 0
    if not args.static and not fails:
        if args.shots:
            os.makedirs(args.shots, exist_ok=True)
        pairs = play(fails, bank, alevel, args.katex_dir, args.shots)
    for line in report:
        print(line)
    if fails:
        for f in fails:
            print("FAIL " + f)
        print("\nFAILED: %d problem(s)" % len(fails))
        return 1
    print("\nPASS: %s; %d A-Level questions; self-test 4/4 planted faults caught%s"
          % (", ".join("%s %d" % (s, len(bank[s])) for s in STAGES), len(alevel),
             "" if args.static else "; %d Stage 1 multiplier pairs marked in Chromium; phones %s typed on the keypad"
             % (pairs, ", ".join("%dx%d" % p for p in PHONES))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
