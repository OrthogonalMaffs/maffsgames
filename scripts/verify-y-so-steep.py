# ---------------------------------------------------------------- one item's findings
def check_item(q, stage, fractions, out_tag):
    errs = []
    st = stage
    try:
        m, c, pts = line_of(q['stem'], st, q)
    except (ValueError, ZeroDivisionError, KeyError, IndexError, AttributeError) as e:
        return ['%s: stem could not be read: %s' % (out_tag, e)]
    if fr(q['line']['m']) != m or fr(q['line']['c']) != c:
        errs.append('%s: the item says m = %s, c = %s but its stem gives m = %s, c = %s' % (out_tag, fr(q['line']['m']), fr(q['line']['c']), m, c))
    if len(q['steps']) != STEPS[st] or q['marks'] != STEPS[st]:
        errs.append('%s: %d steps, %d marks (stage %d has %d)' % (out_tag, len(q['steps']), q['marks'], st, STEPS[st]))
    for s in q['steps']:
        want = {'m': [m], 'c': [c], 'eq': [m, c]}[s['id']]
        got = [fr(k) for k in s['keys']]
        if got != want:
            errs.append('%s: step %s key %s, the stem gives %s' % (out_tag, s['id'], [str(g) for g in got], [str(w) for w in want]))
        if s['id'] == 'eq' and s['labels'] != ['m', 'c']:
            errs.append('%s: the equation step is not typed in two boxes m and c' % out_tag)
        sl_here = stage_slips(st, s['id'], m, c, pts, q['stem'])
        seen = [tuple(got)]
        for sl in s['slips']:
            full = tuple(got[i] if sl['vals'][i] is None else fr(sl['vals'][i]) for i in range(len(got)))
            if full in seen:
                errs.append('%s: a slip equals the answer or another slip: %s' % (out_tag, [str(x) for x in full]))
            seen.append(full)
            if not sl['why']:
                errs.append('%s: a slip with no line' % out_tag)
        for w in sl_here:
            full = tuple(got[i] if w[i] is None else w[i] for i in range(len(got)))
            if full != tuple(got) and full not in seen:
                errs.append('%s: the contract slip %s is not named in step %s' % (out_tag, [str(x) if x is not None else '*' for x in w], s['id']))
    if st == 2:
        f = q['figure']
        if f['m'] != m or f['c'] != c or f['range'] != 6:
            errs.append('%s: the figure data m=%s c=%s is not the stem line' % (out_tag, f['m'], f['c']))
        lat = [(x, int(m * x + c)) for x in range(-6, 7) if m * x + c == int(m * x + c) and -6 <= m * x + c <= 6]
        if len(lat) < 2:
            errs.append('%s: fewer than two lattice points in view' % out_tag)
        for p in f['pts']:
            if tuple(p) not in lat:
                errs.append('%s: figure point %s is not a lattice point on the line in view' % (out_tag, p))
    if not fractions and (m.denominator != 1 or c.denominator != 1 or q['needsFractions']):
        errs.append('%s: a fraction in the whole-number bank (m = %s, c = %s)' % (out_tag, m, c))
    if q['needsFractions'] != (m.denominator != 1 or c.denominator != 1 or (st == 6 and parse_side(blocks(q['stem'])[0].split('=')[1])[0].denominator != 1)):
        errs.append('%s: needsFractions is wrong' % out_tag)
    if not q['worked'] or any(not w for w in q['worked']):
        errs.append('%s: no worked answer' % out_tag)
    last = q['worked'][-1]
    from_eq = re.findall(r'§(y = [^§]*)§', last)
    if not from_eq:
        errs.append('%s: the worked answer does not write y = mx + c in full' % out_tag)
    return errs


def check_engine(page, out):
    data = page.evaluate(GEN_JS)
    rng = random.Random(11)
    info = {}
    for key, d in sorted(data.items()):
        st, fractions = int(key[0]), key[1] == 'f'
        bank = d['bank']
        label = 'stage %d%s' % (st, ' (fractions)' if fractions else '')
        ids = {q['key'] for q in bank}
        info[key] = len(ids)
        if len(ids) < MIN_ITEMS or len(bank) < MIN_ITEMS:
            out.append('%s: only %d distinct items (need %d)' % (label, len(ids), MIN_ITEMS))
        if not d['again']:
            out.append('%s: the bank is not the same on every load (fixed seed)' % label)
        bad = 0
        lines = []
        for i, q in enumerate(bank):
            for e in check_item(q, st, fractions, '%s #%d' % (label, i)):
                bad += 1
                if bad <= 5:
                    out.append(e)
            try:
                lines.append(line_of(q['stem'], st, q))
            except Exception:  # noqa: BLE001
                pass
        if bad > 5:
            out.append('%s: ... and %d more findings' % (label, bad - 5))
        neg = sum(1 for (m, c, p) in lines if m < 0)
        if lines and neg < 0.4 * len(lines):
            out.append('%s: only %d of %d items have a negative gradient (need 40%%)' % (label, neg, len(lines)))
        if st == 5:
            off = sum(1 for (m, c, p) in lines if p and p[0][0] != 0)
            if off < 0.75 * len(lines):
                out.append('%s: the given point is off the y-axis in only %d of %d items (need 75%%)' % (label, off, len(lines)))
        if fractions and st >= 3:
            fracs = [m for (m, c, p) in lines if m.denominator != 1]
            if len(fracs) < 0.15 * len(lines):
                out.append('%s: only %d fractional gradients (Higher includes fractions with denominators 2-5)' % (label, len(fracs)))
            if any(not (2 <= m.denominator <= 5) for m in fracs):
                out.append('%s: a gradient with a denominator outside 2-5' % label)
        for sess in d['sessions']:
            if len(sess) != 6 or len(set(sess)) != 6:
                out.append('%s: a session of %d items, %d distinct' % (label, len(sess), len(set(sess))))
                break
        # the module's marker against ours
        items, want = [], []
        for qi, q in enumerate(bank):
            try:
                m, c, pts = line_of(q['stem'], st, q)
            except Exception:  # noqa: BLE001
                continue
            for si, s in enumerate(q['steps']):
                keys = {'m': [m], 'c': [c], 'eq': [m, c]}[s['id']]
                sl = stage_slips(st, s['id'], m, c, pts, q['stem'])
                for v in probes(keys, sl, rng):
                    raws = [typed(x, rng) for x in v]
                    items.append([key, qi, si, raws])
                    want.append(verdict(keys, sl, [pyfrac(r) for r in raws]))
                items.append([key, qi, si, [''] * len(keys)])
                want.append('unreadable')
                items.append([key, qi, si, ['3/'] + ['1'] * (len(keys) - 1)])
                want.append('unreadable')
        got = page.evaluate(PROBE_JS, items)
        diffs = [(items[i], want[i], got[i]) for i in range(len(items)) if want[i] != got[i]]
        for it, w, g in diffs[:3]:
            out.append('%s: mark() said %s for %s of %s, an independent marker says %s' % (label, g, it[3], bank[it[1]]['stem'], w))
        if len(diffs) > 3:
            out.append('%s: ... and %d more marking differences' % (label, len(diffs) - 3))
        info['probes' + key] = len(items)
    return info


