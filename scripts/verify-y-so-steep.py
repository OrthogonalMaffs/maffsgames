# ---------------------------------------------------------------- our own reader of the printed maths
def num(tok):
    tok = tok.strip()
    m = re.fullmatch(r'(-?)\\frac\{(\d+)\}\{(\d+)\}', tok)
    if m:
        return Fr(int(m.group(2)), int(m.group(3))) * (-1 if m.group(1) else 1)
    return Fr(int(tok))


def parse_side(s):
    """A linear expression in x and y written as printed: -6 - 4x, 3x - 2, x + 7, -\\frac{4}{3}x + 5, 2y, y. -> (cx, cy, k)."""
    s = s.replace(' ', '')
    out = {'x': Fr(0), 'y': Fr(0), '': Fr(0)}
    pos = 0
    pat = re.compile(r'([+-]?)((?:\\frac\{\d+\}\{\d+\})|\d+)?([xy]?)')
    while pos < len(s):
        m = pat.match(s, pos)
        if not m or m.end() == pos:
            raise ValueError('cannot read %r at %d' % (s, pos))
        sign = -1 if m.group(1) == '-' else 1
        coef = num(m.group(2)) if m.group(2) else Fr(1)
        out[m.group(3)] += sign * coef
        pos = m.end()
    return out['x'], out['y'], out['']


def blocks(stem):
    return stem.split('§')[1::2]


def readpt(s):
    m = re.fullmatch(r'\((-?\d+), (-?\d+)\)', s)
    return int(m.group(1)), int(m.group(2))


def line_of(stem, stage, q=None):
    """(m, c, points) from the stem alone; stage 2 has no equation in its stem, the grid IS the question: its line is the
    figure's data, which part 2 reads back from the drawn SVG."""
    b = blocks(stem)
    if stage == 2:
        return Fr(q['figure']['m']), Fr(q['figure']['c']), []
    if stage == 1:
        cx, cy, k = parse_side(b[0].split('=')[1])
        return cx, k, []
    if stage == 3:
        lx, ly, lk = parse_side(b[0].split('=')[0])
        rx, ry, rk = parse_side(b[0].split('=')[1])
        A, B, C = lx - rx, ly - ry, lk - rk                    # A x + B y + C = 0
        return -A / B, -C / B, []
    if stage == 4:
        (x1, y1), (x2, y2) = readpt(b[0]), readpt(b[1])
        m = Fr(y2 - y1, x2 - x1)
        return m, y1 - m * x1, [(x1, y1), (x2, y2)]
    if stage == 5:
        m = parse_side(b[0])[2]
        x1, y1 = readpt(b[1])
        return m, y1 - m * x1, [(x1, y1)]
    if stage == 6:
        mo = parse_side(b[0].split('=')[1])[0]
        x1, y1 = readpt(b[1])
        m = -1 / mo if 'perpendicular' in stem else mo
        return m, y1 - m * x1, [(x1, y1)]
    raise AssertionError(stage)


def fr(pair):
    return Fr(pair[0], pair[1])


def pyfrac(s):
    s = s.strip()
    if not re.fullmatch(r'-?\d+(/\d+)?', s):
        return None
    if '/' in s:
        n, d = s.split('/')
        if int(d) == 0:
            return None
        return Fr(int(n), int(d))
    return Fr(int(s))


def stage_slips(stage, step_id, m, c, pts, stem):
    """The contract's named slips for a step, as lists of values with None for 'any' (written here, apart from the module)."""
    out = []
    inv = (1 / m) if m != 0 else None
    sub = [y + m * x for (x, y) in pts]
    if stage == 1:
        out += [[-m, None]] if m != 0 else []
        out += [[None, -c]] if c != 0 else []
        out += [[c, m]]
    elif stage == 2:
        out += [[-m, None]]
        if (-c) % m == 0 if False else (m != 0 and Fr(-c) / m == int(Fr(-c) / m)):
            out += [[None, Fr(-c) / m]]
        out += [[inv, None]]
    elif stage == 3:
        out += [[-m, None]] if m != 0 else []
        out += [[None, -c]] if c != 0 else []
    else:
        mo = None
        if stage == 6:
            mo = parse_side(blocks(stem)[0].split('=')[1])[0]
        if step_id == 'm':
            out += [[-m]] + ([[inv]] if stage == 4 else [])
            if stage == 6 and 'perpendicular' in stem:
                out += [[1 / mo], [-mo], [mo]]
        elif step_id == 'c':
            out += [[s] for s in sub]
        else:
            out += [[-m, None], [inv, None]] + [[None, s] for s in sub]
    return out


def verdict(keys, slips, typed):
    """right / slip / wrong from our own rules; typed are Fractions."""
    if all(t == k for t, k in zip(typed, keys)):
        return 'right'
    for sl in slips:
        if all(v is None or v == k for v, k in zip(sl, keys)):
            continue                          # a slip whose own values are the right ones names nothing
        if all(v is None or v == t for v, t in zip(sl, typed)):
            return 'slip'
    return 'wrong'


def probes(keys, slips, rng):
    out = []
    n = len(keys)
    out.append(list(keys))
    for sl in slips:
        v = [keys[i] if sl[i] is None else sl[i] for i in range(n)]
        out.append(v)
        for i in range(n):
            if sl[i] is not None:
                w = list(keys)
                w[i] = sl[i]
                out.append(w)
    for i in range(n):
        for d in (-3, -1, 1, 2, 7):
            w = list(keys)
            w[i] += d
            out.append(w)
        w = list(keys)
        w[i] = -w[i]
        out.append(w)
        if keys[i] != 0:
            w = list(keys)
            w[i] = 1 / w[i]
            out.append(w)
    for _ in range(8):
        out.append([Fr(rng.randint(-9, 9), rng.randint(1, 5)) for _ in range(n)])
    uniq = []
    for v in out:
        if v not in uniq:
            uniq.append(v)
    return uniq


def typed(f, rng):
    """A way a student might type a Fraction: lowest terms, or not."""
    if f.denominator == 1 and rng.random() < 0.5:
        return str(f.numerator)
    k = rng.choice([1, 1, 2, 3])
    return '%d/%d' % (f.numerator * k, f.denominator * k)


