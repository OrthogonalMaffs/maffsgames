def check_figure(page, q, where, out):
    f = page.evaluate(FIG_JS)
    if not f or len(f['pts']) != 2:
        out.append('%s: no grid with two points drawn' % where)
        return
    (a, b) = f['pts']
    ux = (b['x'] - a['x']) / (b['d'][0] - a['d'][0])
    uy = (a['y'] - b['y']) / (b['d'][1] - a['d'][1])
    if abs(ux - uy) > 0.01:
        out.append('%s: the grid is not square (%.2f vs %.2f px a unit)' % (where, ux, uy))
    x0 = a['x'] - ux * a['d'][0]
    y0 = a['y'] + uy * a['d'][1]
    m, c = q['figure']['m'], q['figure']['c']
    x1, y1, x2, y2 = f['line']
    for (px, py) in ((x1, y1), (x2, y2)):
        gx, gy = (px - x0) / ux, (y0 - py) / uy
        if abs(gy - (m * gx + c)) > 0.05:
            out.append('%s: the drawn line passes through (%.2f, %.2f), which is not on y = %dx + %d' % (where, gx, gy, m, c))
            break
    for p in q['figure']['pts']:
        if abs(m * p[0] + c - p[1]) > 1e-9:
            out.append('%s: figure point %s is off its own line' % (where, p))
    if f['fs'] and min(f['fs']) < 12:
        out.append('%s: grid text %.1f px (needs 12 or more)' % (where, min(f['fs'])))
    if f['labels'] < 4:
        out.append('%s: the grid is not labelled' % where)


def play_stage(page, st, size, out, full):
    w, h = size
    touch = w <= 600
    fold = h - 40
    where = '%dx%d stage %d' % (w, h, st)
    page.evaluate('window.__ev = []; window.__sub = []')
    page.evaluate('YS.ui.start(%d)' % st)
    expect = 0
    answered = 0
    keytapped = False
    rounds = 6 if full else 1
    for qn in range(rounds):
        page.wait_for_function("YS.ui.state() === 'asking'", timeout=8000)
        q = page.evaluate('YS.ui.question()')
        if q['needsFractions']:
            out.append('%s: an item that needs fractions was offered while fraction entry is off' % where)
        for si, step in enumerate(q['steps']):
            page.wait_for_function("YS.ui.state() === 'asking' && YS.ui.stepIndex() === %d" % si, timeout=8000)
            page.wait_for_timeout(150)
            m = page.evaluate("""() => { const kp = document.getElementById('kpHolder'), t = document.getElementById('qtext').getBoundingClientRect(),
                b = document.querySelector('#answer input').getBoundingClientRect(), r = kp.hidden ? null : kp.getBoundingClientRect();
                return { keys: r ? r.bottom : null, q: t.top, qb: t.bottom, box: b.bottom, sw: document.documentElement.scrollWidth, iw: innerWidth,
                         shown: !kp.hidden && getComputedStyle(kp).display !== 'none' }; }""")
            if touch and not m['shown']:
                out.append('%s q%d: no keypad on a touch screen' % (where, qn))
            if touch and m['keys'] is not None and (m['keys'] > fold + 0.5 or m['q'] < 0):
                out.append('%s q%d step %d: the keypad ends at %d and the question starts at %d: not one screen (fold %d)' % (where, qn, si, m['keys'], m['q'], fold))
